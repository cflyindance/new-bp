/**
 * 从 module-settings-catalog + foh-settings-line-scope 生成 feature-seq-scope.ts
 * 用法：node scripts/generate-feature-seq-scope.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CONFIG_DIR = path.resolve(__dirname, "../src/config");
const CATALOG_PATH = path.join(CONFIG_DIR, "module-settings-catalog.ts");
const FOH_SCOPE_PATH = path.join(CONFIG_DIR, "foh-settings-line-scope.ts");
const OUT_PATH = path.join(CONFIG_DIR, "feature-seq-scope.ts");

/** settingsPath 默认产线（未在 FOH 矩阵中逐项声明时） */
const HUB_DEFAULT_LINES = {
  "/finance/settings": ["pos"],
  "/operations/kitchen-kds/settings": ["pos", "kds"],
  "/operations/kitchen-kds/display": ["kds", "pos"],
  "/operations/kitchen-kds/workflow": ["kds", "pos"],
  "/orders/settings": ["pos", "pos-go", "paypad"],
  "/device-management/settings": ["pos", "kiosk", "kds", "emenu", "paypad"],
  "/print-templates/settings": ["pos", "kds"],
  "/operations/inventory-ordering/settings": [],
  "/operations/reservations/settings": ["pos"],
  "/operations/waitlist/settings": ["online-order"],
};

/** 跨 hub 硬编码 seq（财务 POS 等） */
const SEQ_MANUAL = {
  63: ["pos"],
  64: ["pos"],
  65: ["pos"],
  76: ["pos"],
  171: ["pos"],
  181: ["pos"],
  307: ["pos"],
  330: ["pos"],
};

function parseCatalogSeqPaths(catalogText) {
  const hubBlocks = [...catalogText.matchAll(/"(\/[^"]+)":\s*\{[\s\S]*?items:\s*\[([\s\S]*?)\]\s*,?\s*\}/g)];
  const rows = [];
  for (const [, settingsPath, itemsBlock] of hubBlocks) {
    const seqs = [...itemsBlock.matchAll(/seq:\s*(\d+)/g)].map((m) => Number(m[1]));
    for (const seq of seqs) {
      rows.push({ seq, settingsPath });
    }
  }
  return rows;
}

function parseFohScope(fohText) {
  const map = {};
  const entries = [...fohText.matchAll(/"(\d+)":\s*\{[\s\S]*?"lines":\s*\[([\s\S]*?)\]/g)];
  for (const [, seq, linesRaw] of entries) {
    const lines = [...linesRaw.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
    map[Number(seq)] = { lines, source: "foh-line-scope" };
  }
  return map;
}

function main() {
  const catalogText = fs.readFileSync(CATALOG_PATH, "utf8");
  const fohText = fs.readFileSync(FOH_SCOPE_PATH, "utf8");
  const catalogRows = parseCatalogSeqPaths(catalogText);
  const fohMap = parseFohScope(fohText);

  const scopeBySeq = {};

  for (const { seq, settingsPath } of catalogRows) {
    if (SEQ_MANUAL[seq]) {
      scopeBySeq[seq] = { lines: SEQ_MANUAL[seq], source: "manual", settingsPath };
      continue;
    }
    if (fohMap[seq] && settingsPath.startsWith("/operations/queue-call/settings")) {
      const lines = fohMap[seq].lines.filter((l) => l !== "store-wide");
      if (lines.length > 0) {
        scopeBySeq[seq] = { lines, source: fohMap[seq].source, settingsPath };
      }
      continue;
    }
    const hubLines = HUB_DEFAULT_LINES[settingsPath];
    if (hubLines && hubLines.length > 0) {
      scopeBySeq[seq] = { lines: hubLines, source: "hub-default", settingsPath };
    }
  }

  const sortedKeys = Object.keys(scopeBySeq)
    .map(Number)
    .sort((a, b) => a - b);

  const lines = sortedKeys.map((seq) => {
    const e = scopeBySeq[seq];
    const linesJson = JSON.stringify(e.lines);
    return `  ${seq}: { lines: ${linesJson}, source: "${e.source}", settingsPath: "${e.settingsPath}" },`;
  });

  const out = `/** AUTO-GENERATED by scripts/generate-feature-seq-scope.mjs — do not edit */

import type { ProductLineTag } from "./feature-registry";

export type FeatureSeqScopeSource = "foh-line-scope" | "hub-default" | "manual";

export interface FeatureSeqScopeEntry {
  lines: ProductLineTag[];
  source: FeatureSeqScopeSource;
  settingsPath: string;
}

/** L4：seq → 适用产线；空 lines = 全产线可见 */
export const FEATURE_SEQ_SCOPE: Record<number, FeatureSeqScopeEntry> = {
${lines.join("\n")}
};

export function getFeatureSeqScope(seq: number): FeatureSeqScopeEntry | undefined {
  return FEATURE_SEQ_SCOPE[seq];
}
`;

  fs.writeFileSync(OUT_PATH, out, "utf8");
  console.log(`[generate-feature-seq-scope] Wrote ${sortedKeys.length} seq entries → ${OUT_PATH}`);
}

main();
