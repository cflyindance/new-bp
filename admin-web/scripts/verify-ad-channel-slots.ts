import assert from 'node:assert/strict';
import {defaults,available,snapshot,validateSnapshot,updateContract,newSpec,validateSpecs,validateMedia,samePosition} from '../src/marketing-display/ad-slot-catalog';
import {createPlatformState,saveRegion} from '../src/marketing-display/domain';
const initial=defaults(),home=initial.find(s=>s.code==='home')!;
assert.equal(available(initial,'Kiosk').length,2);assert.equal(available(initial,'eMenu').length,0);
assert.deepEqual(home.specs!.map(s=>[s.width,s.height]),[[1080,1250],[1440,1080]]);
const unbound={...structuredClone(home),id:'emenu-home',productLine:'eMenu',bindings:{}};
assert.equal(available([unbound],'eMenu').length,0);
assert.throws(()=>updateContract(home,{...home,productLine:'eMenu'}),/不可修改/);
assert.throws(()=>updateContract(undefined,{...unbound,productLine:''}),/请选择/);
assert.throws(()=>updateContract(undefined,{...unbound,bindings:home.bindings}),/产线一致/);
assert.throws(()=>validateSpecs([{...newSpec(),width:0}]),/宽高/);
assert.throws(()=>validateSpecs([newSpec(),{...newSpec('second'),name:'另一个'}]),/不得重复/);
const changed=updateContract(home,{...structuredClone(home),specs:home.specs!.map((s,i)=>i? s:{...s,width:1200})});
assert.equal(changed.specVersion,2);assert.equal(home.specVersion,1);assert.equal(changed.specHistory![0].specs[0].width,1080);
assert.equal(updateContract(changed,structuredClone(changed)).specVersion,2);
validateSnapshot([changed],snapshot(home));assert.throws(()=>validateSnapshot([{...home,enabled:false}],snapshot(home)),/不可用/);
const strict={...newSpec(),sizeMode:'strict' as const};const media={kind:'image' as const,mime:'image/png',bytes:1000,width:1080,height:1920};
assert.deepEqual(validateMedia(strict,media),[]);assert.throws(()=>validateMedia(strict,{...media,width:1000}),/须为/);
assert.equal(validateMedia({...strict,sizeMode:'recommend'}, {...media,width:1000}).length,1);
assert.throws(()=>validateMedia(strict,{...media,mime:'image/svg+xml'}),/格式/);
assert.throws(()=>validateMedia(strict,{...media,bytes:6*1024*1024}),/大小/);
assert.throws(()=>validateMedia(strict,{...media,kind:'video',mime:'video/mp4',duration:121}),/时长/);
assert.throws(()=>validateMedia({...strict,mediaKinds:['image']},{...media,kind:'video',mime:'video/mp4',duration:10}),/不支持/);
const input={...unbound,bindings:{eMenu:{minimumVersion:'1.0.0',mediaKinds:['image' as const]}}};
const platform=saveRegion(createPlatformState(),input,true);assert.equal(platform.regions.filter(s=>s.code==='home').length,2);
assert.throws(()=>saveRegion(platform,{...input,id:undefined},true),/编码已存在/);
assert.equal(samePosition({adSlot:snapshot(home)},{adSlot:{...snapshot(home),id:'other',productLine:'eMenu'}}),false);
assert.equal(samePosition({adSlot:snapshot(home)},{adSlot:snapshot(changed)}),true);
console.log('PASS ad slots: channel isolation, scoped uniqueness, access registration, immutable versions, strict/recommended pixels, media type/size/duration, placement conflict identity');
