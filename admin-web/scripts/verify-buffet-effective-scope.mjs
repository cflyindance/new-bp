import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const path='dist/Configuration center/assets/buffet-effective-scope.js';
assert.ok(fs.existsSync(path),'scope time helper exists');
const context=vm.createContext({window:{}});
vm.runInContext(fs.readFileSync(path,'utf8'),context);
const api=context.window.BuffetEffectiveScope;
const c={businessHourSlots:[{id:'lunch',mode:'full'},{id:'dinner',mode:'full'}],businessHourSetupMode:'all_full'};
api.activate(c);
assert.equal(c.scopeTimeVersion,1);
assert.equal(c.businessHourSlots[0].from,'11:00');
assert.equal(c.businessHourSlots[1].to,'23:00');
assert.equal(api.validate(c),null);
assert.match(api.summary(c),/午市 11:00–16:59/);
const custom=(id,name,from,to)=>({id,name,mode:'custom',from,to});
c.businessHourSlots=[custom('custom_1','早餐','08:00','10:00'),custom('custom_2','午餐','10:00','12:00')];
assert.equal(api.validate(c),null,'adjacent half-open intervals allowed');
c.businessHourSlots[1].from='09:59';assert.match(api.validate(c),/重叠/);
c.businessHourSlots[1].from='25:00';assert.match(api.validate(c),/有效时间/);
c.businessHourSlots=[custom('custom_1','早餐','10:00','08:00')];assert.match(api.validate(c),/早于/);
c.businessHourSlots[0].name=' ';assert.match(api.validate(c),/名称/);
c.businessHourSlots=[];api.normalize(c);assert.equal(c.businessHourSlots.length,0);assert.match(api.validate(c),/至少/);
vm.runInContext(fs.readFileSync('dist/Configuration center/assets/buffet-list-query.js','utf8'),context);
c.businessHourSlots=[custom('custom_1','早餐','08:00','10:00')];
c.effectiveFrom='2026-11-01';c.activityCycle='weekly';c.daysOfWeek=['tue'];
assert.equal(context.window.BuffetListQuery.timeMatch({conditions:c},'2026-11-17T09:00'),true);
assert.equal(context.window.BuffetListQuery.timeMatch({conditions:c},'2026-11-17T10:00'),false);
assert.equal(context.window.BuffetListQuery.timeMatch({conditions:c},'2026-11-18T09:00'),false);
assert.match(context.window.BuffetListQuery.timeSummary({conditions:c}),/每周 二；早餐 08:00–10:00/);
vm.runInContext(fs.readFileSync('dist/Configuration center/assets/buffet-rule-domain.js','utf8'),context);
const late=JSON.parse(JSON.stringify(c));late.businessHourSlots=[custom('custom_2','下午','12:00','13:00')];
assert.equal(context.window.BuffetRuleDomain.conditionsOverlap(c,late),false,'custom names do not make disjoint times conflict');
late.businessHourSlots[0].from='09:00';
assert.equal(context.window.BuffetRuleDomain.conditionsOverlap(c,late),true,'explicit custom times participate in conflict detection');
const flow=fs.readFileSync('dist/Configuration center/assets/order-limit-flow.js','utf8');
assert.match(flow,/function renderBuffetEffectiveScope/);
assert.match(flow,/data-scope-slot-add/);
assert.match(flow,/data-scope-slot-name/);
assert.match(flow,/olf-scope-store-grid/);
console.log('PASS effective-scope legacy conversion, custom interval validation and UI bindings');
