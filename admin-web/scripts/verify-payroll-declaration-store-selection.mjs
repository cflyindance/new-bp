import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
const ts = createRequire(import.meta.url)('typescript');
const source = fs.readFileSync(new URL('../src/team/payroll/payroll-declaration-settings.ts', import.meta.url), 'utf8');
const page = fs.readFileSync(new URL('../src/team/payroll-page.ts', import.meta.url), 'utf8');
assert.match(source, /data-declaration-store/);
assert.match(source, /指定门店/);
assert.doesNotMatch(source.match(/createFamily\([^;]+/)?.[0] ?? '', /input\.context\.getScope/);
assert.doesNotMatch(page, /createPayrollDeclarationSettingsController\(\{[^\n]*repository: declarationRepository/);
assert.match(source, /subscribeScopeChange/);
const renderer = source.slice(source.indexOf('function escapeHtml'), source.indexOf('export function createPayrollDeclarationSettingsController'));
const sandbox = { isDeclarationBrowserDemo: () => true };
vm.createContext(sandbox);
vm.runInContext(ts.transpileModule(renderer, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText, sandbox);
const state = { families: [{ familyId: 'enterprise', languageDisplayName: '中文', localeCode: 'zh-CN', scope: { organizationId: 'org' } }, { familyId: 'store', languageDisplayName: '中文', localeCode: 'zh-CN', scope: { organizationId: 'org', storeId: 'B' } }], versions: [], selectedFamilyId: null, stores: [{ id: 'B', labelZh: 'B店' }], draft: { languageDisplayName: '', localeCode: '', source: '', scopeMode: 'enterprise', storeId: 'B' }, editorOpen: true };
const surface = { innerHTML: '' };
sandbox.renderSettings(surface, state);
assert.doesNotMatch(surface.innerHTML, /当前状态/);
assert.deepEqual([...surface.innerHTML.matchAll(/<th scope="col">([^<]+)<\/th>/g)].map(match => match[1]), ['模板名称', '模板范围', '门店', '状态', '使用员工总数', '声明内容', '操作']);
assert.match(surface.innerHTML, /<td>全部门店<\/td>/, 'Enterprise row must have its own store cell');
assert.match(surface.innerHTML, /<td>B店<\/td>/, 'Store row must have its own store cell');
const rows = surface.innerHTML.match(/<tr class="payroll-declaration-table-row[^]*?<\/tr>/g) ?? [];
assert.equal(rows.length, 2);
for (const row of rows) assert.equal((row.match(/<td[ >]/g) ?? []).length, 7);
assert.match(rows[0], /data-declaration-family="enterprise"/);
assert.match(surface.innerHTML, /<label>适用门店<input[^>]*value="全部门店"/, 'New enterprise template must always show its store field');
state.draft.scopeMode = 'store';
sandbox.renderSettings(surface, state);
assert.match(surface.innerHTML, /<label>适用门店<select data-declaration-store/);
assert.match(surface.innerHTML, /value="B" selected>B店/);
state.versions = [{ familyId: 'store', versionId: 'v1', version: 1, status: 'published', source: '<img src=x onerror=alert(1)> {{employee_name}}\n完整正文' }];
sandbox.renderSettings(surface, state);
assert.match(surface.innerHTML, /data-status="published">已发布/);
assert.match(surface.innerHTML, /&lt;img src=x onerror=alert\(1\)&gt; \{\{employee_name\}\}/);
assert.doesNotMatch(surface.innerHTML, /<img/);
assert.match(surface.innerHTML, /payroll-declaration-content-preview" dir="auto"/);
state.filters = {storeId: 'B', scope: 'store', status: 'published'};
state.families[1].activeVersionId = 'v1';
sandbox.renderSettings(surface, state);
assert.doesNotMatch(surface.innerHTML, /data-declaration-family="enterprise"/);
assert.match(surface.innerHTML, /data-declaration-assign-family="store"[^>]*>选择员工/);
state.filters.status = 'retired';
sandbox.renderSettings(surface, state);
assert.match(surface.innerHTML, /暂无符合条件的模板/);
state.filters = {storeId: 'B', scope: '', status: ''};
sandbox.renderSettings(surface, state);
assert.match(surface.innerHTML, /data-declaration-family="enterprise"/);
state.versions.push({familyId:'store',versionId:'v2',version:2,status:'draft',source:'draft'});
state.filters.status = 'draft';
sandbox.renderSettings(surface, state);
assert.match(surface.innerHTML, /data-declaration-delete-family="store"/);
assert.match(surface.innerHTML, />修改<\/button>/);
assert.match(surface.innerHTML, /使用当前已发布版本/);
state.versions[1].status = 'retired';
state.filters.status = 'retired';
state.selectedFamilyId = 'store';
sandbox.renderSettings(surface, state);
assert.doesNotMatch(surface.innerHTML, /data-declaration-delete|data-declaration-save|data-declaration-publish|data-declaration-assign/);
assert.match(surface.innerHTML, /data-declaration-source rows="10" disabled/);
state.families = [];
sandbox.renderSettings(surface, state);
assert.match(surface.innerHTML, /colspan="7"[^>]*>暂无模板/);
const css = fs.readFileSync(new URL('../src/team/payroll/payroll-page.css', import.meta.url), 'utf8');
assert.match(css, /\.payroll-declaration-content-preview\s*\{[^}]*-webkit-line-clamp:\s*2/);
console.log('Declaration store selection UI contracts passed');
