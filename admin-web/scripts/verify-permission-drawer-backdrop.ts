import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {bindDialogBackdropClose} from '../src/permissions/center-dialog-backdrop';
const listeners=new Map<string,(event:any)=>void>();let closes=0;
const dialog={addEventListener:(name:string,fn:(event:any)=>void)=>listeners.set(name,fn),getBoundingClientRect:()=>({left:500,right:1400,top:0,bottom:900}),close:()=>closes++};
bindDialogBackdropClose(dialog as unknown as HTMLDialogElement);
const send=(name:string,x:number,target:unknown=dialog,button=0)=>listeners.get(name)!({target,clientX:x,clientY:100,button});
send('pointerdown',100);send('click',100);assert.equal(closes,1,'backdrop click closes');
send('pointerdown',600);send('click',600);assert.equal(closes,1,'drawer whitespace stays open');
send('pointerdown',100,{});send('click',100,{});assert.equal(closes,1,'child/control click stays open');
send('pointerdown',600);send('click',100);assert.equal(closes,1,'drag from drawer to backdrop does not close');
send('pointerdown',100);send('click',600);assert.equal(closes,1,'drag from backdrop into drawer does not close');
send('pointerdown',100);listeners.get('pointercancel')!({});send('click',100);assert.equal(closes,1);
send('pointerdown',100,dialog,2);send('click',100,dialog,2);assert.equal(closes,1,'right click stays open');
send('click',100);assert.equal(closes,1,'no matching pointerdown does not close');
send('pointerdown',500);send('click',500);assert.equal(closes,1,'drawer boundary stays open');
send('pointerdown',100);send('click',100);assert.equal(closes,2,'subsequent backdrop click still works');
const ui=readFileSync('src/permissions/center-ui.ts','utf8');
const drawer=ui.slice(ui.indexOf('  function showStaffEffective()'),ui.indexOf('  function preview()'));
assert(drawer.includes('bindDialogBackdropClose(dialog)'));
assert.equal((ui.match(/bindDialogBackdropClose\(dialog\)/g)??[]).length,1,'only employee effective drawer opts in');
assert(ui.includes("dialog.addEventListener('close',()=>{dialog.remove();trigger?.focus();})"),'existing close restores focus');
console.log('PASS drawer backdrop: outside closes, interior/children/drag/cancel/right-click stay open, scoped opt-in and focus restore');
