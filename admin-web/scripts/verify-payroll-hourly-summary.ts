import assert from 'node:assert/strict';
import {createPayrollScheduleDemo} from '../src/team/payroll/payroll-schedule-demo';
import {resolveCaliforniaPayroll,renderCaliforniaSummaryView} from '../src/team/payroll/payroll-ca-bridge';
const data=createPayrollScheduleDemo('biweekly','test-store');
const period=data.periods.find(p=>p.startDate==='2027-06-20')!;
const result=resolveCaliforniaPayroll(data.employees[period.id][0],period);
if(result?.status!=='ready')throw Error('ready');
const before=JSON.stringify(result);
const hours=renderCaliforniaSummaryView(result,'hours');
const rate=renderCaliforniaSummaryView(result,'rate');
const amount=renderCaliforniaSummaryView(result,'amount');
const names=(html:string)=>[...html.matchAll(/<dt>(.*?)<\/dt>/g)].map(m=>m[1]);
assert.deepEqual(names(hours),names(rate));assert.deepEqual(names(rate),names(amount));
for(const value of ['$20.00/h','$30.00/h','$40.00/h','$60.00/h','$80.00/h'])assert.ok(rate.includes(value),value);
assert.ok(amount.includes('$4160.00'));assert.ok(amount.includes('$5880.00'));
assert.match(rate,/OT · 3×/);assert.match(rate,/OT · 4×/);assert.match(rate,/合计<\/dt><dd>—/);
assert.doesNotMatch(hours+rate+amount,/<details|<button|data-ca-continuous-help/);
assert.doesNotMatch(hours+rate+amount,/· [34]倍/);
assert.equal((hours.match(/payroll-ca-summary-tier/g)||[]).length,0);
const mixed=structuredClone(result);mixed.slices.push({...mixed.slices.find(s=>s.continuousTier===1)!,regularRate:25});
assert.match(renderCaliforniaSummaryView(mixed,'rate'),/\$75.00\/h/);
assert.deepEqual(names(renderCaliforniaSummaryView(mixed,'hours')),names(renderCaliforniaSummaryView(mixed,'rate')));
const zero={...result,slices:[],totalHours:0,totalAmount:0};
assert.doesNotMatch(renderCaliforniaSummaryView(zero,'rate'),/NaN|Infinity|\$0.00/);
assert.equal(JSON.stringify(result),before);
console.log('PASS aligned hours/rate/income, expanded tiers, subtotal, mixed rates, zero and immutable results.');
