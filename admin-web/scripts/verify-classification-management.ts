import assert from 'node:assert/strict';
const values = new Map<string, string>();
const storage = {getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => values.set(key, value), removeItem: (key: string) => values.delete(key)};
const location = {hash: '#/operations/queue-call/classification-settings/categories'};
Object.assign(globalThis, {localStorage: storage, location, window: Object.assign(new EventTarget(), {location, localStorage: storage})});
const ui = await import('../src/config/foh-classification-settings-ui');
const { NAV_MODULES } = await import('../src/config/navigation');
const {resolvePageSaveKey, initPageSaveSession, discardPageDraft, isPageSaveDirty} = await import('../src/config/page-settings-draft');
const base = ui.FOH_CLASSIFICATION_SETTINGS_BASE;
const branch = NAV_MODULES.find(m => m.id === 'queue-call')!.children.find(c => c.id === 'qc-classification-settings')!;
assert.deepEqual(branch.children!.map(c => [c.title, c.path]), [['分类与菜单', `${base}/categories`], ['分类设置', `${base}/settings`]]);
for (const path of [base, `${base}/categories`, `${base}/settings`]) assert.equal(resolvePageSaveKey(path), base);
initPageSaveSession(base);
const state = ui.readFohClassificationSettingsState();
const category = state.categories[0]!;
state.menuByCategory[category.id]!.viewOnlyCategoryIds = [state.categories[1]!.id];
ui.writeFohClassificationSettingsState(state);
assert(isPageSaveDirty(base));
assert.equal(values.has('bplant-module-setting-field:foh-classification-settings:v1'), false, 'changes must stay in draft');
location.hash = `#${base}/settings`;
assert.equal(ui.readFohClassificationSettingsState().menuByCategory[category.id]!.viewOnlyCategoryIds.length, 1, 'subpage shares menu draft');
location.hash = `#${base}/categories`;
const html = ui.renderFohClassificationSettingsPage(`${base}/categories`);
assert(!html.includes('data-foh-classification-settings-nav'));
assert(html.includes('1 个分类 · 配置'));
assert(!html.includes('不可下单'));
assert(html.includes('data-cls-search'));
const basic = html.split('data-cls-dialog')[1]!.split('data-cls-menu-edit-dialog')[0]!;
assert(!basic.includes('data-brand-menu-structure-picker'), 'basic editor must not contain menu picker');
const settings = ui.renderFohClassificationSettingsPage(`${base}/settings`);
assert(settings.includes('分类模式适用终端'));
assert(!settings.includes('data-cls-table-wrap'));
discardPageDraft(base);
assert.equal(ui.readFohClassificationSettingsState().menuByCategory[category.id]!.viewOnlyCategoryIds.length, 0);
console.log('PASS classification navigation, shared draft, count units, basic/menu separation, settings and discard');

const live = {kiosk: ['d:live-group:live-category:live-dish', 'd:live-group:live-category:live-dish'], emenu: ['d:live-group:live-category:live-dish'], pos: [], sdi: []};
assert.equal(ui.countClassificationConfiguredDishes(live), 2, 'live menu leaves counted once per line');
console.log('PASS host menu dish count and per-line deduplication');
