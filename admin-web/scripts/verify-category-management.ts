import assert from "node:assert/strict";
import { readFohCategorySettingsState, writeFohCategorySettingsState, renderFohCategorySettingsPage, resolveFohCategorySettingsTab } from "../src/config/foh-category-settings-ui.ts";
import { resolvePageSaveKey } from "../src/config/page-settings-draft.ts";
import { readGuestCategoryModeLines, writeGuestCategoryModeLines, GUEST_MENU_CATEGORY_MODE_SEQ } from "../src/config/module-settings-guest-category-mode-ui.ts";
import { writeModuleSettingToggleOn } from "../src/config/module-settings-toggle-ui.ts";

const records = new Map<string, string>();
Object.assign(globalThis, { location: { hash: "#/test" } });
Object.assign(globalThis, { localStorage: { getItem: (key: string) => records.get(key) ?? null, setItem: (key: string, value: string) => records.set(key, value), removeItem: (key: string) => records.delete(key) } });
const base = "/operations/queue-call/category-settings";
assert.equal(resolveFohCategorySettingsTab(`${base}/menu/category/cat-lunch-bbq`), "menu");
assert.equal(resolvePageSaveKey(`${base}/menu/category/cat-lunch-bbq`), base);
const state = readFohCategorySettingsState();
assert.equal(Object.keys(state.menuByCombo).length, state.ages.length * state.categories.length);
assert.ok(Object.values(state.menuByCombo).every((config) => !config.configured), "generated empty configurations are not confirmed");
const [firstKey] = Object.keys(state.menuByCombo);
assert.ok(firstKey);
state.menuByCombo[firstKey]!.viewOnlyCategoryKeys = [firstKey, "deleted-combo"];
writeFohCategorySettingsState(state);
assert.equal(readFohCategorySettingsState().menuByCombo[firstKey]!.configured, false, "invalid and self references do not count as configured content");
state.menuByCombo[firstKey]!.viewOnlyCategoryKeys = [];
state.menuByCombo[firstKey]!.configured = true;
writeFohCategorySettingsState(state);
assert.equal(readFohCategorySettingsState().menuByCombo[firstKey]!.configured, true, "explicit empty configuration survives normalization");
const basic = renderFohCategorySettingsPage(`${base}/age-category`);
assert.ok(basic.includes("年龄标记"));
assert.ok(!basic.includes('role="tablist"'));
const menu = renderFohCategorySettingsPage(`${base}/menu`);
assert.ok(menu.includes("已配置") && menu.includes("未配置"));
assert.ok(menu.includes("仅可查看") && !menu.includes("不可下单"));
assert.ok(menu.includes("data-menu-group"));
writeModuleSettingToggleOn(GUEST_MENU_CATEGORY_MODE_SEQ, true);
const beforeRead = new Map(records);
readGuestCategoryModeLines(GUEST_MENU_CATEGORY_MODE_SEQ);
assert.deepEqual(records, beforeRead, "reading legacy defaults does not persist a new configuration");
writeGuestCategoryModeLines(GUEST_MENU_CATEGORY_MODE_SEQ, []);
assert.deepEqual(readGuestCategoryModeLines(GUEST_MENU_CATEGORY_MODE_SEQ), [], "explicit empty channels override a legacy enabled toggle");
console.log("category management: routes, shared draft key, generated combinations, explicit-empty status and labels passed");
