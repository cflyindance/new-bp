import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const c={window:{}}; vm.createContext(c);
vm.runInContext(fs.readFileSync('src/team/tips/legacy/tipout-summary-ui.js.txt','utf8'),c);
const ui=c.window.TipOutSummaryUi;
const entry={poolId:'p',ruleId:'r',usesHours:true,hours:8,hoursValid:true,source:'original-punch'};
assert.equal(ui.summarizeAllocationHourValues([entry,{...entry,ruleId:'b'}]).display,'8 h ⓘ');
assert.equal(ui.summarizeAllocationHourValues([entry,{...entry,hours:5}]).display,'按规则查看 ›');
assert.equal(ui.summarizeAllocationHourValues([{...entry,usesHours:false}]).display,'不适用');
assert.equal(ui.summarizeAllocationHourValues([{...entry,hoursValid:false}]).display,'待补录');
assert.equal(ui.summarizeAllocationHourValues([entry,{...entry,hoursValid:false}]).display,'按规则查看 ›');
assert.equal(ui.summarizeAllocationHourValues([{...entry,validDays:1,eligibleDays:2}]).display,'按规则查看 ›');
const grouped=ui.aggregateAllocationHourEntries([{dateKey:'2026-09-28',allocationHourEntries:[entry]},{dateKey:'2026-09-29',allocationHourEntries:[{...entry,hoursValid:false}]}]);
assert.equal(ui.allocationHourCoverage(grouped[0]),'1 / 2 天');
assert.equal(ui.allocationHourEntryDisplay(grouped[0]),'8 h（记录不完整）');
assert.equal(ui.allocationHourExplanation({...entry,source:'max-hours'}),'按每日工时上限计入后累计');
assert.equal(ui.allocationHourEntryDisplay({...entry,usesHours:false}),'不适用');
console.log('PASS: rule hours display states, incomplete coverage and calculation descriptions');
