import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const ctx=vm.createContext({structuredClone});
vm.runInContext(fs.readFileSync(new URL('../dist/Configuration center/assets/kiosk-default-ads.js',import.meta.url),'utf8'),ctx);
const p=ctx.KioskDefaultAds;
const slot={id:'k-home',productLine:'Kiosk',code:'home'};
const ad=(id,ids=['1','2'])=>({id,name:id,adPurpose:'default',interactionScope:'brand',adSlot:slot,publishStatus:'published',defaultStoreIds:ids,distributedStores:ids.map(mid=>({mid})),adSlotAssets:{landscape:[{type:'image',clickAction:{type:'none'}}]}});
const old=ad('old'),other={...ad('other'),interactionScope:'other'},draft={...ad('new',[]),publishStatus:'draft'};
const input=[old,other,draft],before=JSON.stringify(input);
const next=p.enable(input,'new',[{name:'A',mid:'1'}],'brand');
assert.equal(JSON.stringify(input),before,'transaction never mutates source before confirmation');
assert.equal(next[0].defaultStoreIds.join(','),'2','partial replacement retains other stores');
assert.equal(next[1].defaultStoreIds.join(','),'1,2','brands isolated');
assert.equal(next[2].publishStatus,'published');
const all=p.enable(next,'new',[{mid:'1'},{mid:'2'}],'brand');
assert.equal(all[0].publishStatus,'draft');assert.equal(p.stores(all[0]).length,0,'empty explicit scope never falls back');
assert.throws(()=>p.enable(input,'new',[],'brand'),/门店/);
assert.throws(()=>p.enable(input,'new',[{mid:'1'}],'other'),/品牌/);
assert.throws(()=>p.validateDefault({...draft,adSlotAssets:{a:[{type:'image',clickAction:{type:'external'}}]}}),/不跳转/);
const campaign={...ad('campaign'),adPurpose:'campaign',distributedStores:[{mid:'1'}],end:100};
const context={scope:'brand',storeId:'1',slot,now:99,ready:()=>true,usable:()=>true,campaignActive:(ad,now)=>now<ad.end,fallback:'builtin'};
assert.equal(p.selectPlayback([campaign,...next],context).kind,'campaign');
assert.equal(p.selectPlayback([campaign,...next],{...context,now:100}).ad.id,'new','expired campaign switches locally at end');
assert.equal(p.selectPlayback([draft],context).kind,'builtin');
assert.equal(p.selectPlayback([],{...context,fallback:'hide'}).kind,'hide');
assert.equal(p.selectPlayback([next[2]],{...context,ready:ad=>ad.id==='old',cachedDefault:old}).ad.id,'old','pending replacement retains downloaded old default');
assert.equal(p.selectPlayback([],{...context,cachedDefault:old}).kind,'builtin','removed assignment cannot revive cached default');
assert.equal(p.selectPlayback([other],context).kind,'builtin');
assert.equal(p.selectPlayback([next[2]],{...context,usable:()=>false}).kind,'builtin');
console.log('PASS default replacement, brand/store isolation, expiry and offline selection contract');
