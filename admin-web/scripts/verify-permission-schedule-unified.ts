applyAuthorization(grants,row,'inherit');for(const key of [row.contentKey,...row.editKeys])assert.equal(grants[key],undefined);
assert.equal(c.resources.get(actionKey(path,'manage-shift'))!.parent,pageKey(`${path}/shifts`));
