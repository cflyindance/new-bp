import assert from 'node:assert/strict';
import type {CenterState,Role} from '../src/permissions/center-domain';
const testLocation=new URL('http://localhost/');
Object.assign(globalThis,{window:Object.assign(new EventTarget(),{location:testLocation}),location:testLocation});
const {buildCenterCatalog}=await import('../src/permissions/center-catalog');
const {buildDemoScenarios}=await import('../src/permissions/center-demo-scenarios');
const {roleAccess,accessibleEmployeeStores}=await import('../src/permissions/center-domain');
const {buildRoleTree,countEffectiveRolePermissions}=await import('../src/permissions/center-role-tree-model');
const {pageMode}=await import('../src/permissions/center-page-mode');
const {validateCenterState}=await import('../src/permissions/center-persistence');

const catalog=buildCenterCatalog();
const stores=[1,2,3,4].map(i=>({id:'M0000000'+i,title:'门店'+i,brand:'b',region:'r'}));
const bare=(id:string):Role=>({id,name:id,description:'',system:false,grants:{}});
const initial:CenterState={schema:1,version:1,roles:[{...bare('store-manager'),grants:{'navigation:team:team-tax-payroll':'read'}},bare('cashier')],employees:[],logs:[]};
const seed=(state:CenterState)=>buildDemoScenarios(state,stores,[],new Date('2026-11-25T00:00:00Z'),catalog.resources).state;
const state=seed(initial),payroll='/team/payroll-report';
const preset=(state:CenterState,key:string)=>state.roles.find(role=>role.id==='permission-scene-v1-'+key)!;
const access=(role:Role,key:string)=>roleAccess(role,key,catalog.resources);
const mode=(role:Role)=>pageMode(catalog,'page:'+payroll,key=>access(role,key));
const action=(role:Role,id:string)=>access(role,'action:'+payroll+':'+id);
const manager=preset(state,'manager'),unscoped=preset(state,'unscoped'),cashier=preset(state,'cashier'),spare=preset(state,'spare');
assert.equal(mode(manager),'edit');
assert.equal(mode(unscoped),'read');
assert.equal(mode(cashier),'hidden');
for(const id of ['export-detail-csv','switch-employee','edit-employee','save-payroll'])assert.equal(action(manager,id),'edit',id);
assert.equal(action(unscoped,'export-detail-csv'),'edit');
for(const id of ['switch-employee','edit-employee','save-payroll'])assert.equal(action(unscoped,id),'hidden',id);
assert.equal(access(cashier,'page:/orders/all'),'read');
assert.deepEqual(unscoped.defaultStoreIds,[]);
assert.deepEqual(spare.defaultStoreIds,[]);
assert.equal(state.employees.some(employee=>employee.bindings.some(binding=>binding.roleId===spare.id)),false);
assert.equal(seed(state),state);
validateCenterState(state,catalog.resources);
const tree=buildRoleTree(catalog);
const count=(role:Role)=>countEffectiveRolePermissions(catalog,tree,role);
assert.equal(count(bare('unassigned')),0);
assert.ok(count(manager)>count(unscoped));
assert.ok(count(unscoped)>0);


const old=structuredClone(state);
old.demoScenarioSeedVersion=1;
preset(old,'manager').grants={};
preset(old,'unscoped').grants={};
old.logs.unshift({id:'manual',at:'2026-11-25',actor:'管理员',objectId:preset(old,'manager').id,action:'更新角色权限',before:'{}',after:'{}'});
const upgraded=seed(old);
assert.deepEqual(preset(upgraded,'manager').grants,{});
assert.equal(mode(preset(upgraded,'unscoped')),'read');
assert.equal(seed(upgraded),upgraded);
console.log('PASS preset payroll edit/read/hidden, independent actions, store scopes, legacy upgrade and manual grant protection');


const extraStaffKeys=['email-enabled','email-disabled','extra-only','overlap','unopened-no-grants','invited-assigned','extra-batch'];
const extraStaffIds=new Set(extraStaffKeys.map(key=>'permission-scene-v1-'+key));
const existingStaff=structuredClone(state);
delete existingStaff.demoStaffScenarioSeedVersion;
existingStaff.employees=existingStaff.employees.filter(employee=>!extraStaffIds.has(employee.id));
existingStaff.logs=existingStaff.logs.filter(log=>!extraStaffIds.has(log.objectId));
const expanded=buildDemoScenarios(existingStaff,stores,[],new Date('2026-11-25T00:00:00Z'),catalog.resources);
const staff=(key:string)=>expanded.state.employees.find(employee=>employee.id==='permission-scene-v1-'+key)!;
assert.equal(expanded.state.employees.length,existingStaff.employees.length+7);
assert.equal(expanded.accounts.length,6);
assert.ok(existingStaff.employees.every(employee=>JSON.stringify(expanded.state.employees.find(item=>item.id===employee.id))===JSON.stringify(employee)));
const accepted=expanded.accounts.find(account=>account.employeeId===staff('email-enabled').id)!;
const disabled=expanded.accounts.find(account=>account.employeeId===staff('email-disabled').id)!;
const invited=expanded.accounts.find(account=>account.employeeId===staff('invited-assigned').id)!;
assert.equal(accepted.openedVia,'email');
assert.equal(accepted.invitation,undefined);
assert.equal(accepted.enabled,true);
assert.equal(disabled.openedVia,'email');
assert.equal(disabled.enabled,false);
assert.ok(invited.invitation);
assert.equal(invited.password,'');
assert.equal(staff('extra-only').bindings.length,0);
assert.equal(accessibleEmployeeStores(staff('extra-only'),expanded.state.roles,stores).length,1);
assert.equal(accessibleEmployeeStores(staff('overlap'),expanded.state.roles,stores).length,2);
assert.equal(staff('unopened-no-grants').email,'');
assert.equal(seed(expanded.state),expanded.state);
validateCenterState(expanded.state,catalog.resources);
console.log('PASS staff scenario upgrade, account lifecycle and scope combinations');


const previousStaff=structuredClone(state);
previousStaff.demoStaffScenarioSeedVersion=1;
const batchId='permission-scene-v1-extra-batch';
previousStaff.employees=previousStaff.employees.filter(employee=>employee.id!==batchId);
previousStaff.logs=previousStaff.logs.filter(log=>log.objectId!==batchId);
const batchSeed=buildDemoScenarios(previousStaff,stores,[],new Date('2026-11-25T00:00:00Z'),catalog.resources);
assert.equal(batchSeed.accounts.length,1);
assert.equal(batchSeed.state.employees.length,previousStaff.employees.length+1);
const batchStaff=batchSeed.state.employees.find(employee=>employee.id===batchId)!;
assert.deepEqual(batchStaff.extraStoreIds,['M00000002','M00000003','M00000001']);
assert.equal(accessibleEmployeeStores(batchStaff,batchSeed.state.roles,stores).length,3);
assert.equal(seed(batchSeed.state),batchSeed.state);
console.log('PASS extra store batch fixture, overlapping grant and one-time upgrade');
