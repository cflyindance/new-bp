import assert from 'node:assert/strict';
import type {CenterState,Role} from '../src/permissions/center-domain';
const testLocation=new URL('http://localhost/');
Object.assign(globalThis,{window:Object.assign(new EventTarget(),{location:testLocation}),location:testLocation});
const {buildCenterCatalog}=await import('../src/permissions/center-catalog');
const {buildDemoScenarios}=await import('../src/permissions/center-demo-scenarios');
const {roleAccess}=await import('../src/permissions/center-domain');
const {buildRoleTree,countEffectiveRolePermissions}=await import('../src/permissions/center-role-tree-model');
const {pageMode}=await import('../src/permissions/center-page-mode');
const {validateCenterState}=await import('../src/permissions/center-persistence');

const catalog=buildCenterCatalog();
const stores=[1,2,3,4].map(i=>({id:'M0000000'+i,title:'门店'+i,brand:'b',region:'r'}));
const bare=(id:string):Role=>({id,name:id,description:'',system:false,grants:{}});
const initial:CenterState={schema:1,version:1,roles:[{...bare('store-manager'),grants:{'navigation:team:team-tax-payroll':'read'}},bare('cashier')],employees:[],logs:[]};
const seed=(state:CenterState)=>buildDemoScenarios(state,stores,[],new Date('2026-11-25T00:00:00Z'),catalog.resources).state;
const state=seed(initial),payroll='/team/payroll-report';
const preset=(state:CenterState,key:string)=>state.roles.find(role=>role.id==='permission-scene-v1-'+key)!;
const access=(role:Role,key:string)=>roleAccess(role,key,catalog.resources);
const mode=(role:Role)=>pageMode(catalog,'page:'+payroll,key=>access(role,key));
const action=(role:Role,id:string)=>access(role,'action:'+payroll+':'+id);
const manager=preset(state,'manager'),unscoped=preset(state,'unscoped'),cashier=preset(state,'cashier'),spare=preset(state,'spare');
assert.equal(mode(manager),'edit');
assert.equal(mode(unscoped),'read');
assert.equal(mode(cashier),'hidden');
for(const id of ['export-detail-csv','switch-employee','edit-employee','save-payroll'])assert.equal(action(manager,id),'edit',id);
assert.equal(action(unscoped,'export-detail-csv'),'edit');
for(const id of ['switch-employee','edit-employee','save-payroll'])assert.equal(action(unscoped,id),'hidden',id);
assert.equal(access(cashier,'page:/orders/all'),'read');
assert.deepEqual(unscoped.defaultStoreIds,[]);
assert.deepEqual(spare.defaultStoreIds,[]);
assert.equal(state.employees.some(employee=>employee.bindings.some(binding=>binding.roleId===spare.id)),false);
assert.equal(seed(state),state);
validateCenterState(state,catalog.resources);
const tree=buildRoleTree(catalog);
const count=(role:Role)=>countEffectiveRolePermissions(catalog,tree,role);
assert.equal(count(bare('unassigned')),0);
assert.ok(count(manager)>count(unscoped));
assert.ok(count(unscoped)>0);


const old=structuredClone(state);
old.demoScenarioSeedVersion=1;
preset(old,'manager').grants={};
preset(old,'unscoped').grants={};
old.logs.unshift({id:'manual',at:'2026-11-25',actor:'管理员',objectId:preset(old,'manager').id,action:'更新角色权限',before:'{}',after:'{}'});
const upgraded=seed(old);
assert.deepEqual(preset(upgraded,'manager').grants,{});
assert.equal(mode(preset(upgraded,'unscoped')),'read');
assert.equal(seed(upgraded),upgraded);
console.log('PASS preset payroll edit/read/hidden, independent actions, store scopes, legacy upgrade and manual grant protection');
