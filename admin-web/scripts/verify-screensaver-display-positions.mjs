import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';

const data = new Map();
const storage = {getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value), removeItem: key => data.delete(key)};
const window = {localStorage: storage};
runInNewContext(readFileSync(new URL('../dist/Configuration center/assets/kiosk-theme-display-positions.js', import.meta.url), 'utf8'), {window});
const positions = window.KioskThemePositions;
const read = () => Array.from(positions.read());
const saved = theme => Array.from(positions.savedForTheme(theme));
assert.deepEqual(saved({distributePositions:['home','screensaver','home','invalid']}), ['screensaver','home']);
assert.deepEqual(saved({distributePositions:['home']}), ['home']);
assert.deepEqual(saved({lastDistributePrefs:{positions:['screensaver']}}), ['screensaver']);
assert.deepEqual(saved({distributePositions:[],lastDistributePrefs:{positions:['home']}}), [], 'explicit empty activity configuration wins over old preference');
assert.deepEqual(saved({distributePositions:null,lastDistributePrefs:{positions:['home']}}), [], 'invalid activity configuration is not replaced by stale preference');
assert.deepEqual(saved({}), [], 'unknown historical records stay unconfigured');
assert.deepEqual(saved({distributePositions:['<img src=x onerror=alert(1)>']}), []);
const original = {distributePositions:['home'],lastDistributePrefs:{positions:['screensaver']}};
const before = JSON.stringify(original);
assert.deepEqual(saved(original), ['home']);
assert.equal(JSON.stringify(original), before, 'rendering must not mutate saved data');
storage.setItem('current_theme_id_for_distribute', 'new');
assert.deepEqual(read(), [], 'new flow starts with no selection');
positions.write(['home', 'screensaver', 'home', 'invalid']);
assert.deepEqual(saved({}), [], 'list configuration does not read current editing draft');
assert.deepEqual(read(), ['screensaver', 'home'], 'multi-select normalizes known options');
positions.write([]);
assert.deepEqual(read(), [], 'explicit empty selection survives return/reload');
storage.setItem('kiosk_themes', JSON.stringify([{id: 'saved', lastDistributePrefs: {positions: ['home']}}, {id: 'legacy'}]));
storage.setItem('current_theme_id_for_distribute', 'saved');
assert.deepEqual(read(), ['home'], 'restore saved preference without leaking other theme draft');
positions.write([]);
assert.deepEqual(read(), [], 'unchecking overrides saved preference');
positions.clear();
assert.deepEqual(read(), ['home']);
storage.setItem('current_theme_id_for_distribute', 'legacy');
assert.deepEqual(read(), [], 'legacy missing field requires explicit selection');
storage.setItem('selected_display_positions_for_distribute', '{bad');
assert.deepEqual(read(), [], 'invalid draft is not a valid position');
storage.setItem('kiosk_themes', 'null');
assert.deepEqual(read(), []);
window.localStorage = {getItem() {throw Error('blocked');}};
assert.deepEqual(read(), [], 'blocked storage cannot silently select a position');
assert.throws(() => positions.write(['home']), 'write errors remain observable by UI');
console.log('PASS screensaver positions: default empty, normalization, scoped draft, explicit empty, saved restore, legacy and storage failure');
