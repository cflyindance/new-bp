import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildCenterCatalog, actionKey, pageKey } from '../src/permissions/center-catalog';
import { additionalPageActions } from '../src/permissions/center-actions';
import { roleAccess, resolveAccess, type CenterState, type Store } from '../src/permissions/center-domain';
import { renderPermissionEditor } from '../src/permissions/center-editor';
import { persistCenterChange } from '../src/permissions/center-persistence';
const catalog=buildCenterCatalog(), path='/team/payroll-report', page=pageKey(path);
const edit=actionKey(path,'edit-employee'), pdf=actionKey(path,'export-detail-pdf'), csv=actionKey(path,'export-detail-csv');
assert.ok(catalog.resources.has(edit),'Payroll edit employee must have an independent action');
assert.ok(catalog.resources.has(pdf));assert.ok(catalog.resources.has(csv));
assert.equal(additionalPageActions[path].length,21);
const grants:Record<string,'read'|'edit'|'hidden'>={[edit]:'edit'};
let ancestor:string|undefined=page;
while(ancestor){grants[ancestor]='read';ancestor=catalog.resources.get(ancestor)?.parent;}
const state:CenterState={schema:1,navigationVersion:1,version:0,logs:[],roles:[{id:'r',name:'薪资编辑',description:'',system:false,grants}],employees:[{id:'e',name:'员工',email:'test@example.com',status:'enabled',bindings:[{id:'b',roleId:'r',scope:{mode:'stores',ids:['a']}}],overrides:{}}]};
const stores:Store[]=[{id:'a',title:'A',brand:'brand',region:'east'},{id:'b',title:'B',brand:'brand',region:'east'}];
const value=(key:string)=>roleAccess(state.roles[0],key,catalog.resources);
assert.equal(value(edit),'edit');assert.equal(value(pdf),'hidden');assert.equal(value(csv),'hidden');
for(const action of additionalPageActions[path])if(action.id!=='edit-employee')assert.equal(value(actionKey(path,action.id)),'hidden','New action must not be implicitly granted');
const options={catalog,page,group:'',preview:false,readonly:false,staff:false,value,own:(key:string)=>state.roles[0].grants[key]??'hidden',search:''} as const;
const html=renderPermissionEditor(options);
assert.match(html,/编辑员工信息/);assert.match(html,/导出薪资明细 PDF/);
assert.ok(html.includes(`data-grant="${pdf}"`));
let preview=renderPermissionEditor({...options,preview:true});
assert.match(preview,/<button type="button" data-demo >编辑员工信息<\/button>/);
assert.match(preview,/<button type="button" data-demo disabled title="暂无操作权限">导出薪资明细 PDF<\/button>/);
state.roles[0].grants[edit]='hidden';state.roles[0].grants[pdf]='edit';
assert.equal(value(edit),'hidden');assert.equal(value(pdf),'edit');assert.equal(value(csv),'hidden');
preview=renderPermissionEditor({...options,preview:true});
assert.match(preview,/<button type="button" data-demo >导出薪资明细 PDF<\/button>/);
assert.equal(resolveAccess(state,'e','a',pdf,stores,catalog.resources),'edit');
assert.equal(resolveAccess(state,'e','b',pdf,stores,catalog.resources),'hidden');
state.employees[0].overrides.a={[pdf]:'hidden',[edit]:'edit'};
assert.equal(resolveAccess(state,'e','a',pdf,stores,catalog.resources),'hidden');
assert.equal(resolveAccess(state,'e','a',edit,stores,catalog.resources),'edit');
delete state.employees[0].overrides.a[pdf];
assert.equal(resolveAccess(state,'e','a',pdf,stores,catalog.resources),'edit');
state.roles[0].grants[page]='hidden';
assert.equal(value(pdf),'hidden');assert.equal(resolveAccess(state,'e','a',edit,stores,catalog.resources),'hidden');
assert.equal(state.roles[0].grants[pdf],'edit');state.roles[0].grants[page]='read';
const parent=catalog.resources.get(page)!.parent!;state.roles[0].grants[parent]='hidden';
assert.equal(value(pdf),'hidden');state.roles[0].grants[parent]='read';assert.equal(value(pdf),'edit');
let saved=JSON.stringify(state);
const storage={getItem:()=>saved,setItem:(_key:string,data:string)=>{saved=data;}};
persistCenterChange(storage,'test',state,0,'r','编辑权限','动作回归',catalog.resources);
const restored:CenterState=JSON.parse(saved);
assert.equal(roleAccess(restored.roles[0],pdf,catalog.resources),'edit');assert.equal(roleAccess(restored.roles[0],csv,catalog.resources),'hidden');
assert.ok(catalog.resources.has(actionKey('/team/roles-employees','edit-employee')));
assert.ok(catalog.resources.has(actionKey('/team/roles-employees','edit-role')));
assert.ok(catalog.resources.has(actionKey('/team/tips/details','confirm-allocation')));
assert.ok(catalog.resources.has(actionKey('/team/tips/distribution','export-csv')));
assert.ok(!additionalPageActions['/team/reports/payroll'],'Do not create actions on the placeholder payroll statistics page');
assert.match(readFileSync('src/permissions/center-ui.ts','utf8'), /dialog\.addEventListener\('keydown',[\s\S]*?Escape[\s\S]*?stopPropagation\(\)/, 'Escape in a permission dialog must not bubble into the shell and reset the draft');
console.log('PASS: payroll 21 independent source-backed actions, default denial, export/edit isolation, ancestor restore, per-store overrides, persistence and preview');
