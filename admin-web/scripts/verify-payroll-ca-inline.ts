import assert from 'node:assert/strict';
import {createPayrollScheduleDemo} from '../src/team/payroll/payroll-schedule-demo';
import {resolveCaliforniaPayroll,renderCaliforniaSummary,renderCaliforniaDayBreakdown} from '../src/team/payroll/payroll-ca-bridge';
const data=createPayrollScheduleDemo('biweekly','test-store');
const period=data.periods.find(p=>p.startDate==='2027-06-20')!;
assert.ok(period);
const employee=data.employees[period.id][0];
const result=resolveCaliforniaPayroll(employee,period);
assert.equal(result?.status,'ready');if(result?.status!=='ready')throw Error('ready');
const before=JSON.stringify(result);
const summary=renderCaliforniaSummary(result,false);
assert.doesNotMatch(summary,/<button|data-ca-overtime/);
for(const name of ['OT','OT2','每周加班','第7天加班'])assert.ok(summary.includes(name));
const rows=result.slices.filter(s=>s.date==='2027-06-26');
const html=renderCaliforniaDayBreakdown(rows);
assert.match(html,/<details/);assert.match(html,/<summary>计薪明细 · 2027-06-26<\/summary>/);
assert.match(html,/8\.00 h × \$20\.00 × 1\.5 = \$240\.00/);
assert.match(html,/2\.00 h × \$20\.00 × 2 = \$80\.00/);
assert.match(html,/320\.00/);assert.match(html,/第7天加班/);
assert.match(html,/0\.00–8\.00 h/);assert.match(html,/8\.00–10\.00 h/);
assert.doesNotMatch(renderCaliforniaDayBreakdown(result.slices.filter(s=>s.date==='2027-06-21')),/<details/);
assert.equal(renderCaliforniaDayBreakdown([]),'');
const dirty=renderCaliforniaDayBreakdown([{...rows[0],evidence:'<img onerror="bad">'}]);
assert.doesNotMatch(dirty,/<img/);assert.match(dirty,/&lt;img/);
assert.equal(JSON.stringify(result),before);
const frozen={...employee,confirmed:true,californiaOvertimeInput:undefined,californiaOvertimeSnapshot:result};
assert.deepEqual(resolveCaliforniaPayroll(frozen,period),result);
console.log('PASS plain summary, inline two-tier formulas, regular/zero, escaping and frozen snapshot.');
