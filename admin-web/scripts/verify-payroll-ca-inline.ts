import assert from 'node:assert/strict';
import {createPayrollScheduleDemo} from '../src/team/payroll/payroll-schedule-demo';
import {resolveCaliforniaPayroll,renderCaliforniaSummary,renderCaliforniaDayBreakdown} from '../src/team/payroll/payroll-ca-bridge';
const data=createPayrollScheduleDemo('biweekly','test-store');
const period=data.periods.find(p=>p.startDate==='2027-06-20')!;
assert.ok(period);
const employee=data.employees[period.id][0];
const result=resolveCaliforniaPayroll(employee,period);
assert.equal(result?.status,'ready');if(result?.status!=='ready')throw Error('ready');
const before=JSON.stringify(result);
const summary=renderCaliforniaSummary(result,false);
assert.doesNotMatch(summary,/data-ca-overtime/);
for(const name of ['OT','OT2','每周加班','连勤加班'])assert.ok(summary.includes(name));
const rows=result.slices.filter(s=>s.date==='2027-06-26');
const html=renderCaliforniaDayBreakdown(rows);
assert.match(html,/<details/);assert.match(html,/<summary>计算依据 · 2027-06-26<\/summary>/);
assert.doesNotMatch(html,/<details[^>]*\bopen|当日合计|<strong>Regular|当日累计/);
assert.match(html,/连勤加班/);assert.match(html,/\$60\.00\/h/);assert.match(html,/\$80\.00\/h/);
assert.match(html,/\$360\.00/);assert.match(html,/\$160\.00/);
assert.doesNotMatch(renderCaliforniaDayBreakdown(result.slices.filter(s=>s.date==='2027-06-21')),/<details/);
assert.equal(renderCaliforniaDayBreakdown([]),'');
const dirty=renderCaliforniaDayBreakdown([{...rows[0],kind:'continuous',evidence:'<img onerror="bad">'}]);
assert.doesNotMatch(dirty,/<img/);assert.match(dirty,/&lt;img/);
assert.equal(JSON.stringify(result),before);
const frozen={...employee,confirmed:true,californiaOvertimeInput:undefined,californiaOvertimeSnapshot:result};
assert.deepEqual(resolveCaliforniaPayroll(frozen,period),result);
const sample=rows[0];
assert.equal(renderCaliforniaDayBreakdown(['regular','daily','daily-double'].map(kind=>({...sample,kind:kind as typeof sample.kind,evidence:'单日规则'}))),'');
for(const kind of ['weekly','continuous','seventh-day'] as const){
  const rendered=renderCaliforniaDayBreakdown([{...sample,kind,evidence:'累计超过40小时'}]);
  assert.match(rendered,/计算依据/);assert.match(rendered,/累计超过40小时/);
}
const mixed=renderCaliforniaDayBreakdown([{...sample,kind:'regular'},{...sample,kind:'daily',evidence:'普通OT'},{...sample,kind:'weekly',evidence:'周累计超过40小时'}]);
assert.match(mixed,/每周加班/);assert.doesNotMatch(mixed,/<strong>Regular|<strong>OT|当日合计/);
assert.match(renderCaliforniaDayBreakdown([{...sample,kind:'daily',evidence:'同分钟取最高倍率。'}]),/计算依据/);
console.log('PASS selective calculation basis, actual hourly rate, no regular/day total, default collapsed, escaping and frozen snapshot.');
