import assert from 'node:assert/strict';
import {createPayrollScheduleDemo} from '../src/team/payroll/payroll-schedule-demo';
import {resolveCaliforniaPayroll,renderCaliforniaSummary,renderCaliforniaDayBreakdown} from '../src/team/payroll/payroll-ca-bridge';
import {renderCalculationBasis} from '../src/team/payroll/payroll-calculation-popover';
const data=createPayrollScheduleDemo('biweekly','test-store');
const period=data.periods.find(p=>p.startDate==='2027-06-20')!;
const employee=data.employees[period.id][0],result=resolveCaliforniaPayroll(employee,period);
if(result?.status!=='ready')throw Error('ready');
const before=JSON.stringify(result),rows=result.slices.filter(s=>s.date==='2027-06-26');
assert.match(renderCaliforniaSummary(result,false),/OT · 3×/);
const trigger=renderCaliforniaDayBreakdown(rows);
assert.match(trigger,/<button/);assert.match(trigger,/data-ca-basis-date="2027-06-26"/);
assert.match(trigger,/aria-expanded="false"/);assert.doesNotMatch(trigger,/<details|<tr|<ul/);
const html=renderCalculationBasis(rows,result.continuousRule);
assert.match(html,/连勤加班 · 5天/);assert.match(html,/累计超过50至60小时/);assert.match(html,/累计超过60小时/);
assert.ok(html.includes('6.00 h × $60.00/h'));assert.ok(html.includes('4.00 h × $80.00/h'));
assert.ok(html.includes('$360.00'));assert.ok(html.includes('$320.00'));
assert.equal((html.match(/class="payroll-ca-basis-group"/g)||[]).length,2);
assert.doesNotMatch(html,/Regular|当日合计|当日累计|第7天新增/);
assert.match(html,/按最高时薪/);
assert.equal(renderCaliforniaDayBreakdown([]),'');assert.equal(renderCalculationBasis([]),'');
const sample=rows[0];
const routine=['regular','daily','daily-double'].map(kind=>({...sample,kind:kind as typeof sample.kind,evidence:'单日规则'}));
assert.match(renderCaliforniaDayBreakdown(routine),/计算依据/);assert.match(renderCalculationBasis(routine),/每日加班/);
assert.equal(renderCaliforniaDayBreakdown(routine.filter(s=>s.kind==='regular')),'');
for(const kind of ['weekly','continuous','seventh-day'] as const)assert.match(renderCaliforniaDayBreakdown([{...sample,kind}]),/计算依据/);
const weekly=renderCalculationBasis([{...sample,kind:'weekly',evidence:'周规则'}]);
assert.match(weekly,/周普通工时超过40小时/);assert.doesNotMatch(weekly,/按最高时薪/);
const dirty=renderCalculationBasis([{...sample,kind:'daily',evidence:'最高倍率 <img onerror="bad">'}]);
assert.doesNotMatch(dirty,/<img/);assert.match(dirty,/&lt;img/);
const frozen={...employee,confirmed:true,californiaOvertimeInput:undefined,californiaOvertimeSnapshot:result};
assert.deepEqual(resolveCaliforniaPayroll(frozen,period),result);assert.equal(JSON.stringify(result),before);
console.log('PASS click trigger, grouped tiers/rates, concise conditions, conditional overlap note, escaping and immutable snapshot.');
