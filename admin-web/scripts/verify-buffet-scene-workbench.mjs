import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../dist/Configuration center/assets/order-limit-flow.js',import.meta.url),'utf8');
const start=source.indexOf('  function renderQuantitySceneDialog(');
const end=source.indexOf('  function closeQuantitySceneDialog(',start);
const editorState={quantitySceneDialog:{combo:{period:'multi_round',partyIndex:0,roundIndex:0}}};
const ctx=vm.createContext({editorState,stores:[{id:'s',name:'测试店'}],esc:String,periodLabel:()=> '分轮次',v4ScenarioTitle:()=> '1 人 · 1 轮',normalizeBuffetQuantityWorkbenchState:()=>({selectedIds:['a']}),quantityScenarioIndexes:()=>[{partyIndex:0,roundIndex:0},{partyIndex:0,roundIndex:1}],renderV4PeriodScenario:()=>'<div class="olf-v4-workbench-batch">数量</div>'});
vm.runInContext(source.slice(start,end),ctx);
let html=ctx.renderQuantitySceneDialog({activeStoreId:'s'},{});
assert.ok(html.includes('场景 1 / 2'));
assert.ok(html.includes('保存并返回'));
assert.ok(html.includes('data-quantity-scene-next>'));
assert.ok(html.includes('批量设置（1）'));
assert.ok(html.includes('aria-expanded="false"'));
editorState.quantitySceneDialog.batchOpen=true;
editorState.quantitySceneDialog.combo.roundIndex=1;
html=ctx.renderQuantitySceneDialog({activeStoreId:'s'},{});
assert.ok(html.includes('场景 2 / 2'));
assert.ok(html.includes('data-quantity-scene-next disabled'));
assert.ok(html.includes('olf-scene-workbench is-batch-open'));
editorState.quantitySceneDialog=null;
assert.equal(ctx.renderQuantitySceneDialog({},{}),'');
console.log('verify-buffet-scene-workbench: PASS');
