import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('../dist/Configuration center/assets/kiosk-ad-target-policy.js', import.meta.url), 'utf8'), context);
const p = context.KioskAdTargetPolicy;
const slot = {id:'a',productLine:'Kiosk',code:'screensaver',version:1};
const draft = {id:'draft',publishStatus:'draft',publicationHistory:'never',adSlot:slot,distributeChannels:['Kiosk'],distributePositions:['screensaver'],distributedStores:[{mid:'1'}],lastDistributePrefs:{stores:[{mid:'1'}],startDate:'2026-12-01',endDate:'2026-12-02'}};
assert.equal(p.canEditTarget(draft),true);
const unknown = {...draft}; delete unknown.publicationHistory;
assert.equal(p.canEditTarget(unknown),false);
const published = structuredClone(draft); p.markPublished(published,'2026-11-16T00:00:00Z'); published.publishStatus='published';
assert.equal(p.canEditTarget(published),false);
p.preserveHistory(published,published); published.publishStatus='draft';
assert.equal(p.canEditTarget(published),false,'takedown never unlocks');
const edited=p.prepareSave(published,{...published,publishStatus:'draft'});
assert.equal(edited.publicationHistory,'published');
const other = {...slot,id:'b',code:'home'};
assert.throws(()=>p.assertSave(published,draft,other),/状态已变化/);
assert.throws(()=>p.assertSave(unknown,unknown,other),/不能修改/);
assert.throws(()=>p.prepareSave(unknown,{...unknown,adSlot:other}),/不能修改/);
assert.throws(()=>p.assertSave(undefined,draft,other),/删除/);
assert.doesNotThrow(()=>p.assertSave(published,published,slot));
assert.throws(()=>p.assertSave(published,published,{...slot,version:2}),/不能修改/);
assert.throws(()=>p.assertSave(published,published,{...slot,productLine:'Waitlist'}),/不能修改/);
const changed=p.prepareSave(draft,{...draft,adSlot:other});
assert.equal(changed.distributedStores.length,0);
assert.equal(changed.lastDistributePrefs.stores.length,0);
assert.equal(changed.lastDistributePrefs.startDate,'2026-12-01');
assert.equal(draft.distributedStores.length,1,'source remains unchanged');
assert.equal(p.canEditTarget({...draft,hasEverPublished:true}),false);
assert.equal(p.canEditTarget({...draft,distributeTime:'2026/11/15 12:00'}),false);
assert.equal(p.canEditTarget({...draft,id:'copy'}),true,'copies receive independent explicit never');
for(const file of ['screensaver-create.html','screensaver-edit.html','kiosk-theme-list.html','effective-time.html']) {
  const html=fs.readFileSync(new URL('../dist/Configuration center/'+file,import.meta.url),'utf8');
  assert.match(html,/kiosk-ad-target-policy.js/);
  for(const script of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new vm.Script(script[1],{filename:file});
}
console.log('PASS ad target policy: publication lifecycle, unknown history, stale save, target identity, range reset, native syntax');
