import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../dist/Configuration center/assets/order-limit-flow.js', import.meta.url), 'utf8');
const start = source.indexOf('  function renderBuffetQuantityRanges(');
const end = source.indexOf('  function enabledPeriodsHaveConfiguredQuantity(', start);
assert.ok(start >= 0 && end > start);
const editorState = {};
const ctx = vm.createContext({editorState, ensureBuffetScenarioModel(){}, esc:String, icon:()=>''});
vm.runInContext(source.slice(start,end),ctx);
const draft={subject:'party_size',enabledPeriods:['multi_round'],partyRanges:[{min:1,max:null}],roundRanges:[{min:1,max:1},{min:2,max:null}]};
let html=ctx.renderBuffetQuantityRanges(draft);
assert.ok(html.includes('data-range-dialog-open="party"'));
assert.ok(html.includes('data-range-dialog-open="round"'));
assert.ok(!html.includes('<table'));
assert.ok(!html.includes('<dialog'));
assert.ok(!ctx.renderBuffetQuantityRanges({...draft,subject:'order',enabledPeriods:['per_round']}));
assert.ok(!ctx.renderBuffetQuantityRanges({...draft,subject:'order'}).includes('data-range-dialog-open="party"'));
editorState.rangeCollectionDialog={kind:'round',ranges:structuredClone(draft.roundRanges)};
editorState.rangeCollectionDialog.ranges[0].max=3;
assert.equal(draft.roundRanges[0].max,1,'弹框编辑副本不得修改原区间');
html=ctx.renderBuffetQuantityRanges(draft);
assert.ok(html.includes('id="rangeCollectionDialog"'));
assert.ok(html.includes('轮次区间'));
assert.ok(html.includes('data-range-dialog-save'));
assert.ok(html.includes('data-range-dialog-cancel'));
assert.ok(html.includes('data-range-dialog-add'));
assert.ok(html.includes('data-range-dialog-delete="1"'));
editorState.rangeCollectionDialog=null;
assert.ok(!ctx.renderBuffetQuantityRanges(draft).includes('<dialog'));
console.log('verify-buffet-range-collections: PASS');
