const { createRequire } = require('node:module');
const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = process.env.TIPOUT_BROWSER_PACKAGES ? createRequire(path.join(process.env.TIPOUT_BROWSER_PACKAGES,'package.json'))('playwright') : require('playwright');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(process.env.TIPOUT_PREVIEW_URL || 'http://127.0.0.1:65021/');
    await page.evaluate(async () => {
      localStorage.clear();
      const { mountLegacyTipsRuntime } = await import('/src/team/tips/tips-legacy-runtime.ts');
      const { renderTipsTemplate } = await import('/src/team/tips/tips-templates.ts');
      const store = 'Golden Dragon Chinese Kitchen - Dallas, TX 75231';
      localStorage.setItem('tipout-employees-roster-v1',JSON.stringify(['Server','Bartender','Busser','Runner','Host','Cashier'].map((role,i)=>({id:'test-'+i,name:['Maria Garcia','Mike Johnson','Carlos Lopez','Daniel Ortiz','Rachel Scott','Linda Nguyen'][i],role,store,active:true}))));
      document.body.innerHTML = '<div id="test-host"></div>';
      const shadow = document.querySelector('#test-host').attachShadow({mode:'open'});
      const root = document.createElement('div'); shadow.append(root);
      const context = {getScope:()=>({storeId:store,storeLabel:store,storeLabelEn:store,isAllStores:false,usesInPageStorePicker:true,stores:[{id:store,labelZh:store,labelEn:store}]}),setStoreScope:()=>{},subscribeScopeChange:()=>()=>{},navigate:href=>window.testNavigation=href,replace:()=>{},getNavigationState:()=>null,getScrollOwner:()=>null};
      window.mountTest = () => { window.testRuntime?.destroy(); root.innerHTML=renderTipsTemplate('distribution'); window.testRuntime=mountLegacyTipsRuntime(shadow,root,{view:'distribution',query:'',href:'/team/tips/distribution'},context); };
      window.mountRulesTest = () => { window.testRuntime?.destroy(); root.innerHTML=renderTipsTemplate('rules'); window.testRuntime=mountLegacyTipsRuntime(shadow,root,{view:'rules',query:'',href:'/team/tips/rules'},context); };
      window.mountDetailTest = date => { window.testRuntime?.destroy(); root.innerHTML=renderTipsTemplate('details'); const query='?store='+encodeURIComponent(store)+'&date='+date; window.testRuntime=mountLegacyTipsRuntime(shadow,root,{view:'details',query,href:'/team/tips/details'+query},context); };
      window.mountTest();
      const rules=JSON.parse(localStorage.getItem('tipout_rules')); rules.forEach(r=>r.clockin='clock'); localStorage.setItem('tipout_rules',JSON.stringify(rules));
      window.mountTest();
    });
    const button = page.locator('.tipout-quick-allocate').first();
    await button.waitFor();
    const storageBeforeList = await page.evaluate(()=>JSON.stringify(Object.fromEntries(Object.entries(localStorage))));
    await page.getByRole('button',{name:'测试场景清单',exact:true}).click();
    assert.equal(await page.locator('[data-scenario-employee-id]').evaluateAll(rows=>new Set(rows.map(r=>r.dataset.scenarioEmployeeId)).size),6);
    assert.match(await page.locator('#tipoutScenarioDialog').textContent(),/POS有效工时/);
    const dialog = page.getByRole('dialog',{name:'测试场景清单',exact:true});
    const centered=await dialog.evaluate(el=>{const r=el.getBoundingClientRect();return Math.abs(r.x+r.width/2-innerWidth/2)<2 && Math.abs(r.y+r.height/2-innerHeight/2)<2;});
    assert.equal(centered,true,'scenario modal must be centered in viewport');
    const allRows=await dialog.locator('[data-scenario-employee-id]').count();
    await dialog.getByRole('searchbox',{name:'搜索',exact:true}).fill('carlos');
    assert.ok(await dialog.locator('[data-scenario-employee-id]').count()>0);
    assert.ok((await dialog.locator('[data-scenario-employee-id]').allTextContents()).every(text=>text.includes('Carlos Lopez')));
    await dialog.getByLabel('考勤状态',{exact:true}).selectOption('未打卡');
    assert.ok((await dialog.locator('[data-scenario-employee-id]').allTextContents()).every(text=>text.includes('未打卡')));
    await dialog.getByLabel('角色',{exact:true}).selectOption('Server');
    assert.equal(await dialog.locator('[data-scenario-employee-id]').count(),0);
    assert.equal(await dialog.getByRole('button',{name:'导出 CSV'}).isDisabled(),true);
    await dialog.getByRole('button',{name:'重置'}).click();
    assert.equal(await dialog.locator('[data-scenario-employee-id]').count(),allRows);
    await dialog.getByLabel('场景类型',{exact:true}).selectOption('B01');
    assert.ok((await dialog.locator('[data-scenario-employee-id]').allTextContents()).every(text=>text.includes('B01')));
    const downloadPromise=page.waitForEvent('download');
    await dialog.getByRole('button',{name:'导出 CSV'}).click();
    const csvDownload=await downloadPromise;
    const csvText=require('node:fs').readFileSync(await csvDownload.path(),'utf8');
    assert.equal(csvText.split('\r\n').length-1,await dialog.locator('[data-scenario-employee-id]').count());
    assert.ok(csvText.split('\r\n').slice(1).every(line=>line.includes('B01')));
    await page.setViewportSize({width:600,height:800});
    assert.ok(await dialog.evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight;}));
    await page.setViewportSize({width:1280,height:720});
    await page.getByRole('button',{name:'关闭',exact:true}).click();
    assert.equal(await page.evaluate(()=>JSON.stringify(Object.fromEntries(Object.entries(localStorage)))),storageBeforeList);
    const date = await button.evaluate(el => el.closest('tr').dataset.date);
    await button.click();
    await page.waitForFunction(() => Object.keys(JSON.parse(localStorage.getItem('tipout_allocation_results_v1')||'{}')).length > 0);
    const results = await page.evaluate(() => JSON.parse(localStorage.getItem('tipout_allocation_results_v1')));
    assert.equal(Object.keys(results).length,1);
    const snapshot = Object.values(results)[0];
    assert.equal(snapshot.dateKey,date);
    assert.equal(snapshot.scenarioFacts.length,6);
    assert.equal(snapshot.employeeContributions.length,6);
    assert.ok(snapshot.employeeContributions.every(row=>Number.isFinite(row.amount) && row.amount>=0));
    assert.equal(snapshot.summary.originalTips,Math.round(snapshot.scenarioFacts.reduce((sum,f)=>sum+f.originalTips,0)*100)/100);
    assert.ok(snapshot.pools.length > 0);
    assert.ok(snapshot.pools.some(p=>p.employees.length));
    const absent = snapshot.pools.flatMap(p=>p.employees).filter(e=>e.attendanceStatus==='absent');
    assert.ok(absent.length > 0, 'fixture must include unclocked employees');
    assert.ok(absent.every(e=>e.amount===0 && e.hours===0));
    assert.equal(await page.locator(`tr[data-date="${date}"] .tipout-quick-allocate`).count(),0);
    assert.equal(await page.evaluate(()=>window.testNavigation),undefined);
    await page.locator('#employeeReconciliationTab').click();
    assert.match(await page.locator('#employeeReconciliationPanel').textContent(), /部分待分配/);
    assert.match(await page.locator('#employeeReconciliationPanel').textContent(), /\$[\d,]+\.\d{2}/);
    await page.evaluate(()=>{const rules=JSON.parse(localStorage.getItem('tipout_rules')); rules[0].clockin='noclock';localStorage.setItem('tipout_rules',JSON.stringify(rules));window.mountTest();});
    await page.locator('#dateTaskTab').click();
    const secondDate = await page.locator('.tipout-quick-allocate').first().evaluate(el=>el.closest('tr').dataset.date);
    const navigationBeforeQuick = await page.evaluate(()=>window.testNavigation);
    await page.locator('.tipout-quick-allocate').first().click();
    await page.waitForFunction(()=>Object.keys(JSON.parse(localStorage.getItem('tipout_allocation_results_v1'))).length===2);
    assert.equal(await page.evaluate(()=>window.testNavigation),navigationBeforeQuick);
    await page.evaluate(date=>window.mountDetailTest(date),date);
    assert.equal(await page.locator('#confirmDetailAllocationBtn').isDisabled(),true);
    assert.ok(await page.locator('.tipout-attendance-label').count() > 0);
    assert.ok(await page.locator('.tipout-attendance-label').filter({hasText:'未打卡'}).count() > 0);
    const before = await page.evaluate(()=>localStorage.getItem('tipout_allocation_results_v1'));
    await page.evaluate(date=>window.mountDetailTest(date),date);
    assert.equal(await page.evaluate(()=>localStorage.getItem('tipout_allocation_results_v1')),before);
    const pct = page.locator('tr[data-attendance-status="clock"] .detail-emp-pct-input').first();
    await pct.fill('25'); await pct.dispatchEvent('change');
    assert.equal(await page.locator('#confirmDetailAllocationBtn').isEnabled(),true);
    assert.equal(await page.locator('#confirmDetailPayoutBtn').isDisabled(),true);
    assert.equal(await page.evaluate(()=>localStorage.getItem('tipout_allocation_results_v1')),before);
    page.once('dialog',dialog=>dialog.dismiss());
    await page.getByRole('button',{name:'返回汇总',exact:true}).click();
    assert.equal(await pct.inputValue(),'25');
    await page.evaluate(()=>{window.originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(key,value){if(key==='tipout_allocation_results_v1')throw new Error('test save failure');return window.originalSetItem.call(this,key,value);};});
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('#confirmDetailAllocationBtn').click();
    await page.waitForFunction(()=>!document.querySelector('#test-host').shadowRoot.querySelector('#confirmDetailAllocationBtn').disabled);
    assert.equal(await page.evaluate(()=>localStorage.getItem('tipout_allocation_results_v1')),before);
    assert.equal(await pct.inputValue(),'25');
    assert.equal(await page.locator('#confirmDetailPayoutBtn').isDisabled(),true);
    await page.evaluate(()=>{Storage.prototype.setItem=window.originalSetItem;});
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('#confirmDetailAllocationBtn').click();
    await page.waitForFunction(previous=>localStorage.getItem('tipout_allocation_results_v1')!==previous,before);
    await page.waitForFunction(()=>document.querySelector('#test-host').shadowRoot.querySelector('#confirmDetailAllocationBtn').disabled);
    assert.equal(await page.locator('#confirmDetailPayoutBtn').isEnabled(),true);
    await page.evaluate(date=>window.mountDetailTest(date),date);
    assert.equal(await pct.inputValue(),'25');
    await pct.fill('30');
    await pct.dispatchEvent('change');
    page.once('dialog',dialog=>dialog.dismiss());
    await page.locator('#detailDate').fill('2026-09-22');
    await page.locator('#detailDate').dispatchEvent('change');
    assert.equal(await page.locator('#detailDate').inputValue(),date);
    page.once('dialog',dialog=>dialog.accept());
    await page.getByRole('button',{name:'返回汇总',exact:true}).click();
    await page.evaluate(date=>window.mountDetailTest(date),date);
    assert.equal(await pct.inputValue(),'25');
    await page.evaluate(date=>window.mountDetailTest(date),secondDate);
    await page.waitForFunction(()=>Object.keys(JSON.parse(localStorage.getItem('tipout_allocation_results_v1'))).length===2);
    await page.waitForFunction(()=>document.querySelector('#test-host').shadowRoot.querySelector('#confirmDetailAllocationBtn').disabled);
    assert.deepEqual(errors,[]);
    const clockHours = await page.locator('tr[data-attendance-status="clock"] .detail-emp-hours-input').evaluateAll(inputs=>inputs.map(i=>({hours:Number(i.value),readonly:i.readOnly})));
    assert.ok(clockHours.length > 0);
    assert.ok(clockHours.every(i=>i.hours>0 && i.readonly));
    const snapshotsBeforeDemo = await page.evaluate(()=>localStorage.getItem('tipout_allocation_results_v1'));
    await page.evaluate(()=>window.mountRulesTest());
    assert.equal(await page.locator('.tipout-rule-name').filter({hasText:'【演示】'}).count(),8);
    await page.evaluate(()=>window.mountRulesTest());
    assert.equal(await page.locator('.tipout-rule-name').filter({hasText:'【演示】'}).count(),8);
    assert.equal(await page.evaluate(()=>localStorage.getItem('tipout_allocation_results_v1')),snapshotsBeforeDemo);
    assert.deepEqual(errors,[]);
    console.log('Quick allocation, snapshot editing and demo rules page seeding passed');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
