import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const c={}; vm.createContext(c);
vm.runInContext(fs.readFileSync('src/team/tips/legacy/tipout-employee-weights.js.txt','utf8'),c);
const w=c.TipOutEmployeeWeights, arr=x=>Array.from(x);
assert.equal(w.read({},'Server','A'),1);
assert.equal(w.read({employeeWeights:{Server:{A:0}}},'Server','A'),0);
for(const bad of ['',null,-1,Infinity,'bad']) assert.throws(()=>w.parse(bad));
assert.deepEqual(arr(w.split(10000,[1,2])),[3333,6667]);
assert.deepEqual(arr(w.split(10000,[4*2,8*1])),[5000,5000]);
assert.deepEqual(arr(w.split(10000,[2*3,3*1])),[6667,3333]);
assert.deepEqual(arr(w.split(10000,[0,0])),[0,0]);
assert.deepEqual(arr(w.split(101,[1,1,1])),[34,34,33]);
console.log('PASS: employee weights defaults, zero, validation and cent apportionment');
vm.runInContext(fs.readFileSync('src/team/tips/legacy/tipout-time-window.js.txt','utf8'),c);
const at=t=>'2026-09-28T'+t+':00-05:00';
const people=['A','B'].map((name,i)=>({employeeId:name,name,role:'Server',attendance:{punchSessions:[{status:'complete',clockInAt:at('18:00'),clockOutAt:at(i?'22:00':'19:00')}]},orders:[]}));
const event=(time,amount)=>({id:time,occurredAt:at(time),amount,timeZone:'America/Chicago'});
const timed=c.TipOutTimeWindow.allocate([event('18:30',90),event('19:30',60)],people,{employeeWeights:{Server:{A:2,B:1}}});
assert.deepEqual(arr(timed.employeeAmounts).map(p=>[p.employeeId,p.amount]),[['A',60],['B',90]]);
assert.equal(c.TipOutTimeWindow.allocate([event('18:30',90)],people,{employeeWeights:{Server:{A:0,B:0}}}).unallocated,90);
console.log('PASS: time-local weights never include an off-duty employee; all-zero remains unallocated');
c.window=c;
vm.runInContext(fs.readFileSync('src/team/tips/legacy/tipout-funding.js.txt','utf8'),c);
const rule={id:'r',distribution:'average',clockin:'unrestricted',receivers:[{roles:['Server'],pct:100,employeeWeights:{Server:{A:2,B:1}}}],funding:{version:1,priority:1,method:'balance',tipSources:['order'],formulas:[{source:'tips',rate:10}],groups:[{kind:'role',values:['Server']}]}};
const facts=['A','B'].map(name=>({employeeId:name,name,role:'Server',originalTips:100,orderTips:100,reportedTips:0,attendance:{effectiveHours:8,punchSessions:[{}]},orders:[{id:name,tipAmount:100,salesAmount:100}]}));
const calc=overrides=>c.TipOutFunding.calculate([rule],facts,'2026-09-28',overrides);
assert.deepEqual(arr(calc().pools[0].employees).map(e=>e.amount),[13.33,6.67]);
assert.deepEqual(arr(calc({r:{A:{employeeWeight:0}}}).pools[0].employees).map(e=>e.amount),[0,20]);
assert.throws(()=>calc({r:{A:{employeeWeight:-1}}}),/权重/);
assert.equal(rule.receivers[0].employeeWeights.Server.A,2);
console.log('PASS: funding engine configured and daily override weights; defaults unchanged');
