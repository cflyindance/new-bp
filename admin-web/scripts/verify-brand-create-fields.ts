import assert from "node:assert/strict";
import { formatBid, generateNextBid, generateNextMid } from "../src/config/enterprise-merchant-bid";
import type { EnterpriseMerchantSnapshot } from "../src/config/enterprise-merchant-types";
const snapshot = { merchants: [{ bid: "B00001233", code: "legacy" }, { bid: "B00000001", code: "B00001234" }], stores: [], posStoreRequests: [], bidSeq: 1234, midSeq: 1 } as unknown as EnterpriseMerchantSnapshot;
assert.equal(formatBid(1234), "B00001234");
assert.equal(generateNextBid(snapshot), "B00001235", "Default brand code must not reuse an occupied legacy code");
assert.equal(snapshot.bidSeq, 1236);
assert.equal(generateNextMid(snapshot), "M00000001");
const exhausted = { ...snapshot, bidSeq: 99999999, merchants: [{ bid: "B99999999", code: "legacy" }] } as unknown as EnterpriseMerchantSnapshot;
assert.throws(() => generateNextBid(exhausted), /编号/, "Exhausted sequence must not produce a nine-digit code");
assert.equal(exhausted.bidSeq, 99999999);
const { validateBrandCreationFields } = await import("../src/config/brand-create-validation");
const valid = { name: "新品牌", businessTypeIds: ["full-service"], productLineIds: ["pos"] };
assert.doesNotThrow(() => validateBrandCreationFields(valid), "Contact is optional");
assert.doesNotThrow(() => validateBrandCreationFields({ ...valid, contactName: "  " }));
assert.throws(() => validateBrandCreationFields({ ...valid, name: " " }), /品牌名称/);
assert.throws(() => validateBrandCreationFields({ ...valid, name: "牌".repeat(61) }), /60/);
assert.throws(() => validateBrandCreationFields({ ...valid, contactName: "联".repeat(31) }), /30/);
assert.throws(() => validateBrandCreationFields({ ...valid, businessTypeIds: [] }), /经营业态/);
assert.throws(() => validateBrandCreationFields({ ...valid, productLineIds: [] }), /产线/);
assert.doesNotThrow(() => validateBrandCreationFields({ ...valid, businessTypeIds: ["full-service", "hotpot"], productLineIds: ["pos", "emenu"] }));
console.log("PASS brand creation field rules and B+8-digit default-code collision protection");
