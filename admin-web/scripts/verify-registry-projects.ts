import assert from 'node:assert/strict';
import { readRegistryWorkspace, updateRegistryWorkspace, registerProjectPage, REGISTRY_PROJECTS_KEY } from '../src/config/page-registry-projects';
import { LOCAL_PAGE_REGISTRATIONS_KEY, buildLocalPageRegistration } from '../src/config/local-page-registration';
const data = new Map<string, string>();
const storage = { getItem: (k: string) => data.get(k) ?? null, setItem: (k: string, v: string) => { data.set(k, v); } };
const legacy = buildLocalPageRegistration({ id: 'legacy', title: '历史', module: '模块', type: 'inner', path: '/legacy' });
data.set(LOCAL_PAGE_REGISTRATIONS_KEY, JSON.stringify({ version: 1, pages: [legacy] }));
assert.equal(readRegistryWorkspace([], storage).workspace.pages.length, 1);
updateRegistryWorkspace([], w => { w.projects.push({ id: 'p', name: '自定义项目' }); w.directories.push({ id: 'a', projectId: 'p', parentId: null, name: '一级' }, { id: 'b', projectId: 'p', parentId: 'a', name: '二级' }); }, storage);
const before = data.get(REGISTRY_PROJECTS_KEY);
assert.throws(() => updateRegistryWorkspace([], w => { w.directories[0].parentId = 'b'; }, storage), /循环/);
assert.equal(data.get(REGISTRY_PROJECTS_KEY), before);
assert.throws(() => updateRegistryWorkspace([], w => { w.projects.push({ id: 'q', name: '自定义项目' }); }, storage), /重复/);
registerProjectPage({ id: 'new', title: '新页面', module: '模块', type: 'inner', path: '/new' }, 'p', 'b', [], storage);
assert.equal(readRegistryWorkspace([], storage).workspace.pages.length, 2);
assert.equal(readRegistryWorkspace([], storage).workspace.assignments[0].directoryId, 'b');
assert.equal(JSON.parse(data.get(LOCAL_PAGE_REGISTRATIONS_KEY)!).pages.length, 1);
const snapshot = data.get(REGISTRY_PROJECTS_KEY);
assert.throws(() => registerProjectPage({ id: 'new2', title: '失败', module: '模块', type: 'inner', path: '/new2' }, 'p', null, [], { ...storage, setItem: () => { throw new Error('quota'); } }), /保存失败/);
assert.equal(data.get(REGISTRY_PROJECTS_KEY), snapshot);
data.set(REGISTRY_PROJECTS_KEY, '{broken'); assert.ok(readRegistryWorkspace([], storage).error);
assert.throws(() => updateRegistryWorkspace([], () => {}, storage), /无法读取/);
data.delete(REGISTRY_PROJECTS_KEY); data.set(LOCAL_PAGE_REGISTRATIONS_KEY, '{broken');
assert.throws(() => updateRegistryWorkspace([], () => {}, storage), /无法读取/);
assert.equal(data.has(REGISTRY_PROJECTS_KEY), false);
console.log('PASS registry projects: migration, atomic writes, duplicate names, hierarchy/cycles, assignments, corrupt and quota protection');
