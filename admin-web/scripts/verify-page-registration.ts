import assert from "node:assert/strict";
import { bindRegisteredPage, matchRegisteredPage, searchPageRegistrations, validatePageRegistrations, type PageRegistration } from "../src/config/page-registration-domain";
import { getPageRegistrations } from "../src/config/page-registration-catalog";
import { serializeMenuDocument } from "../src/config/json-menu-document-serializer";
import type { MenuNode } from "../src/config/json-menu-document-domain";
const product: PageRegistration = { id: "test.products", title: "商品", titleEn: "Products", module: "商品中心", status: "active", source: "test", routing: { type: "inner", path: "/products" } };
const pages = getPageRegistrations();
assert(pages.length > 20);
assert.deepEqual(validatePageRegistrations(pages), []);
assert(validatePageRegistrations([product, product]).length >= 2);
assert(validatePageRegistrations([{ ...product, routing: { type: "inner", path: "//bad" } }]).length);
assert.deepEqual(searchPageRegistrations([product], "products"), [product]);
assert.deepEqual(searchPageRegistrations([product], "不存在"), []);
assert.deepEqual(searchPageRegistrations([product], "", "retired"), []);
const original: MenuNode = { id: "stable-id", key: "stable-key", name: "我的入口", type: "external", path: "/old", url: "https://example.com", externalConfig: { target: "_blank" }, i18nInfo: { "zh-CN": "自定义" }, accessControl: { bool: true, permission: { rule: "every", value: ["existing.permission"] } }, extraInfo: ["preserve"], display: false };
const before = structuredClone(original), bound = bindRegisteredPage(original, product);
assert.deepEqual(original, before);
assert.equal(bound.path, "/products"); assert.equal(bound.type, "inner"); assert.equal(bound.url, undefined); assert.equal(bound.externalConfig, undefined);
for (const key of ["id", "key", "name", "i18nInfo", "accessControl", "extraInfo", "display"] as const) assert.deepEqual(bound[key], original[key], `保留 ${key}`);
assert.equal(matchRegisteredPage(bound, [product])?.id, product.id);
assert.equal(matchRegisteredPage({ ...bound, url: "https://custom.example.com" }, [product]), undefined);
assert.throws(() => bindRegisteredPage(original, { ...product, status: "retired" }));
assert.throws(() => bindRegisteredPage({ ...original, children: [{ id: "child" }] }, product));
const micro: PageRegistration = { ...product, id: "test.micro", routing: { type: "micro-app", path: "/micro", microAppConfig: { name: "app", url: "https://app.example.com", keepAlive: true, iframe: true } } };
const microNode = bindRegisteredPage(bound, micro);
assert.deepEqual(microNode.microAppConfig, micro.routing.microAppConfig);
assert.equal(bindRegisteredPage(microNode, product).microAppConfig, undefined);
const doc = serializeMenuDocument({ _id: "doc", name: "test", menu: [bound], updatedBy: { userId: "test", timestamp: "2026-11-06", firstname: "Test", lastname: null }, createdDate: 0 });
assert.equal(matchRegisteredPage(JSON.parse(JSON.stringify(doc)).menu[0], [product])?.id, product.id);
assert.equal("pageId" in doc.menu[0]!, false);
assert.deepEqual(doc.menu[0]?.accessControl, original.accessControl);
console.log(`PASS: 页面注册、绑定与原 JSON 合同回归；实际目录 ${pages.length} 项`);
