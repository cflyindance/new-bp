import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
const dir=await mkdtemp(join(process.env.BRAND_DECORATION_TEST_TEMP||tmpdir(),'brand-decoration-'));
try{
  await Promise.all(['domain','store','schedule','plans','palette'].map(name=>build({entryPoints:[`src/brand-decoration/${name}.ts`],bundle:true,platform:'node',format:'esm',outfile:join(dir,name+'.mjs')})));
  const D=await import(pathToFileURL(join(dir,'domain.mjs'))),S=await import(pathToFileURL(join(dir,'store.mjs')));
  const C=await import(pathToFileURL(join(dir,'palette.mjs')));
  for(const id of [...Object.keys(C.PALETTES),'custom']){
    for(const color of ['#808080','#fff2c5','#0a1830']){
      const palette=C.resolvePalette(id,color);
      assert.ok(C.contrast(palette.primary,palette.onPrimary)>=4.5);
      assert.ok(C.contrast(palette.ink,palette.background)>=4.5);
    }
  }
  const themed=D.newScheme('kiosk','方案','品牌');
  const old=D.copy(themed);delete old.paletteId;D.validateScheme(old);
  themed.styles.home.theme='noir';
  assert.equal(themed.paletteId,'system');
  assert.equal(themed.primary,C.PALETTES.system.primary);
  const changed={...themed,paletteId:'indigo',primary:C.PALETTES.indigo.primary};
  D.validateScheme(changed);
  assert.ok(D.changes(themed,changed).some(item=>item.label==='方案主题色'&&item.after==='靛蓝'));
  console.log('PASS: palette contrast, legacy compatibility and publication differences.');
  const values=new Map(),storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v)};
  let data=S.readData('brand-a/store-a','甲品牌',storage);
  assert.equal(data.schemes[0].styles.home.mode,'default');assert.equal(Object.keys(data.schemes[0].styles).length,24);
  assert.equal(data.schemes[0].id,S.readData('brand-a/store-a','甲品牌',storage).schemes[0].id,'seed IDs survive route remount');
  const kiosk=data.schemes[0];kiosk.styles.home={mode:'custom',theme:'noir'};
  data=S.writeData('brand-a/store-a',data,0,storage);
  assert.equal(S.readData('brand-a/store-a','甲品牌',storage).schemes[0].styles.home.theme,'noir');
  for(const scope of ['brand-a/store-b','brand-b/store-a'])assert.equal(S.readData(scope,'其他品牌',storage).schemes[0].styles.home.mode,'default','scope isolation');
  assert.equal(data.schemes[1].styles.home.mode,'default','channel isolation');
  assert.throws(()=>S.writeData('brand-a/store-a',data,0,storage),/其他窗口/);
  const release=D.publish(data,kiosk.id,'demo','甲品牌·A店');assert.equal(release.version,1);
  data.schemes[0].brandName='改名';assert.equal(release.snapshot.brandName,'甲品牌','immutable snapshot');
  const second=D.publish(data,kiosk.id,'demo','甲品牌·A店');assert.equal(second.version,2);
  assert.throws(()=>D.publish(data,kiosk.id,'demo','甲品牌·A店'),/无需重复发布/);
  const emenu=data.schemes[1];assert.equal(D.publish(data,emenu.id,'demo','甲品牌·A店').version,1,'channel versions independent');
  const bad=D.copy(data);bad.schemes[0].primary='javascript:alert(1)';assert.throws(()=>D.validateData(bad));
  const before=storage.getItem(S.storageKey('brand-a/store-a'));
  assert.throws(()=>S.writeData('brand-a/store-a',data,1,{...storage,setItem:()=>{throw Error('quota')}}),/存储空间/);
  assert.equal(storage.getItem(S.storageKey('brand-a/store-a')),before,'failed write leaves previous data');
  values.set(S.storageKey('broken'),'{');assert.throws(()=>S.readData('broken','',storage),/损坏/);
  const A=await import(pathToFileURL(join(dir,'schedule.mjs')));
  const activity={id:'winter',channel:'kiosk',name:'冬季',releaseId:release.id,starts:100,ends:200,pageIds:['home']};
  A.saveActivity(data,activity);
  data.schedule.defaults.kiosk=second.id;
  assert.equal(A.resolveSchedule(data,'kiosk',99).active,undefined);
  assert.equal(A.resolveSchedule(data,'kiosk',100).activeRelease.id, release.id);
  assert.equal(A.resolveSchedule(data,'kiosk',200).fallback.id, second.id);
  assert.equal(A.resolveSchedule(data,'emenu',100).active,undefined);
  assert.throws(()=>A.saveActivity(data,{...activity,id:'conflict',starts:199,ends:201}),/重叠/);
  A.saveActivity(data,{...activity,id:'next',starts:200,ends:300});
  assert.equal(A.resolveSchedule(data,'kiosk',200).active.id,'next');
  activity.endedAt=150;
  assert.equal(A.resolveSchedule(data,'kiosk',150).active,undefined);
  assert.equal(A.parseLocal('2026-12-01T10:00','Asia/Shanghai'),Date.parse('2026-12-01T02:00Z'));
  assert.throws(()=>A.parseLocal('2026-11-01T01:30','America/New_York'),/重复/);
  assert.throws(()=>A.parseLocal('2026-03-08T02:30','America/New_York'),/不存在/);
  const P=await import(pathToFileURL(join(dir,'plans.mjs')));
  const stores=[{id:'a',name:'甲店',timezone:'Asia/Shanghai'},{id:'b',name:'乙店',timezone:'Asia/Shanghai'}];
  const flow=S.readData('flow','甲品牌',storage);
  const makePlan=(name,rules)=>({...D.newScheme('kiosk',name,'甲品牌'),rules});
  const daily=makePlan('日常',{kind:'default',storeIds:['a','b'],timezone:'Asia/Shanghai',pageIds:['home']});
  P.publishPlan(flow,daily,stores,'demo');
  const start=Date.now()+3600000,end=start+3600000;
  const winter=makePlan('冬季',{kind:'activity',activityName:'冬季活动',starts:start,ends:end,storeIds:['a'],timezone:'Asia/Shanghai',pageIds:['home']});
  P.publishPlan(flow,winter,stores,'demo');
  assert.equal(P.planPage(flow,'a','kiosk','home',start).snapshot.id,winter.id);
  assert.equal(P.planPage(flow,'a','kiosk','menu',start).snapshot.id,daily.id);
  assert.equal(P.planPage(flow,'b','kiosk','home',start).snapshot.id,daily.id);
  assert.equal(P.planPage(flow,'a','kiosk','home',end).snapshot.id,daily.id);
  assert.throws(()=>P.checkPlanPublication(flow,makePlan('重叠',winter.rules),stores),/甲店.*冬季活动/);
  assert.doesNotThrow(()=>P.checkPlanPublication(flow,makePlan('相邻',{...winter.rules,starts:end,ends:end+1000}),stores));
  assert.throws(()=>P.validatePlanRules({...winter.rules,storeIds:['a','b']},'kiosk',[stores[0],{...stores[1],timezone:'America/New_York'}]),/同一时区/);
  assert.throws(()=>P.validatePlanRules({...winter.rules,storeIds:['unknown']},'kiosk',stores),/有权/);
  const newDaily=makePlan('新日常',{...daily.rules,storeIds:['a']});
  P.publishPlan(flow,newDaily,stores,'demo');
  assert.equal(P.planPage(flow,'a','kiosk','home',end).snapshot.id,newDaily.id);
  assert.equal(P.planPage(flow,'b','kiosk','home',end).snapshot.id,daily.id);
  console.log('PASS: multi-store plans, partial pages, overlaps, timezone and latest fallback.');
  console.log('PASS: activity boundaries, overlap, fallback, channel isolation and time zones.');
  console.log('PASS: seed stability; 24 pages; persistence; brand/store/channel isolation; revision conflicts; immutable snapshots; independent versions; duplicate publish; validation; storage failure; corrupt data.');
}finally{await rm(dir,{recursive:true,force:true});}
