import assert from 'node:assert/strict';
import {calculateContinuousOvertime} from '../src/team/payroll/payroll-continuous-overtime';
const rule={id:'continuous-1',scope:'continuous',dayNumber:5,hoursBeforeOvertime:50,secondaryHoursBeforeOvertime:60,wageMultiplier:3,secondaryWageMultiplier:4};
const days=[0,12,12,12,12,15].map((hours,i)=>({date:`2026-11-${String(i+1).padStart(2,'0')}`,workedMinutes:hours*60,regularRate:20}));
const input={rule,periodStart:'2026-11-02',periodEnd:'2026-11-06',days};
const before=JSON.stringify(input);
const result=calculateContinuousOvertime(input);
assert.equal(result.status,'ready');if(result.status!=='ready')throw Error('ready');
assert.deepEqual(result.slices.map(s=>[s.date,s.streakDay,s.minutes,s.multiplier,s.amount]),[['2026-11-06',5,600,3,600],['2026-11-06',5,180,4,240]]);
assert.equal(result.totalHours,13);assert.equal(result.totalAmount,840);
assert.equal(result.slices[0].dayFromMinute,120);assert.equal(result.slices[0].streakFromMinute,3000);
assert.equal(JSON.stringify(input),before);
const early=calculateContinuousOvertime({...input,rule:{...rule,hoursBeforeOvertime:10,secondaryHoursBeforeOvertime:20}});
if(early.status!=='ready')throw Error('ready');
assert.ok(early.slices.every(s=>s.date==='2026-11-06'));assert.equal(early.totalHours,15);
const period=calculateContinuousOvertime({...input,periodStart:'2026-11-06'});
assert.deepEqual(period,result);
assert.equal(calculateContinuousOvertime({...input,days:days.slice(1)}).status,'blocked');
assert.equal(calculateContinuousOvertime({...input,days:days.filter((_,i)=>i!==2)}).status,'blocked');
assert.equal(calculateContinuousOvertime({...input,days:[...days,days[5]]}).status,'blocked');
const reset=calculateContinuousOvertime({...input,days:days.map((d,i)=>i===4?{...d,workedMinutes:0}:d)});
if(reset.status!=='ready')throw Error('ready');assert.equal(reset.totalHours,0);
