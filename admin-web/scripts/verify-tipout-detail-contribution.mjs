import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={window:{},document:{addEventListener(){}}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('src/team/tips/programs/employee-reconciliation.js.txt','utf8'),context);
const confirmed={dateKey:'2026-09-28',allocated:true,before:100,deducted:10,received:5,after:95,hours:8,clockStatus:'已打卡'};
const pending={...confirmed,dateKey:'2026-09-29',allocated:false,estimatedDeducted:20};
const result=context.summarizeEmployeeDetailRows([confirmed,pending]);
assert.equal(result.confirmedContributionCents,1000);
assert.equal(result.estimatedContributionCents,2000);
assert.equal(result.after,95);
assert.equal(result.received,5);
assert.equal(context.employeeDetailAllocationMoney(pending,0,'deduct'),'-$20.00（预计）');
assert.equal(context.employeeDetailAllocationMoney(pending,0,'receive'),'—');
assert.equal(context.summarizeEmployeeDetailRows([pending]).confirmedContributionCents,0);
assert.equal(context.summarizeEmployeeDetailRows([{...pending,estimatedDeducted:undefined}]).contributionErrors.length,1);
assert.equal(context.summarizeEmployeeDetailRows([{...pending,contributionPreviewError:'入池缺口'}]).contributionErrors[0],'入池缺口');
assert.equal(context.summarizeEmployeeDetailRows(context.filterEmployeeDetailRows([confirmed,pending],'2026-09-29','2026-09-29','全部状态','待分配')).estimatedContributionCents,2000);
console.log('PASS: daily contribution estimates, mixed/filtered totals, errors and export labels');
