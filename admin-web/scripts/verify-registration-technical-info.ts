import assert from 'node:assert/strict';
import {renderRegistrationTechnicalInfo} from '../src/config/page-registration-technical-info';
import type {RegistryWorkspace} from '../src/config/page-registry-projects';
const page={id:'page',title:'商品<script>',module:'模块',status:'active' as const,source:'测试',routing:{type:'micro-app' as const,path:'/products/list'}};
const w:RegistryWorkspace={version:2,projects:[{id:'p',name:'商品中心',productOwner:' 产品<负责人> ',engineeringOwner:'研发负责人甲'}],directories:[{id:'folder',name:'商品管理',projectId:'p',parentId:null},{id:'node',name:'商品',projectId:'p',parentId:'folder',pageId:'page'}],pages:[page],assignments:[{pageId:'page',projectId:'p',directoryId:'folder'}]};
const html=renderRegistrationTechnicalInfo(page,w);
assert.equal((html.match(/<dt /g)??[]).length,5);
assert.ok(html.includes('商品管理 / 商品'));
const flat=renderRegistrationTechnicalInfo(page,{...w,directories:[w.directories[0]]});assert.ok(flat.includes('商品管理 / 商品&lt;script&gt;'));
assert.ok(html.indexOf('所属项目')<html.indexOf('产品负责人'));
assert.ok(html.includes('商品中心'));assert.ok(html.includes('产品&lt;负责人&gt;'));assert.ok(html.includes('研发负责人甲'));assert.ok(html.includes('/products/list'));
assert.ok(!html.includes('完整页面路由参数 JSON'));
const withoutProject=renderRegistrationTechnicalInfo(page,{...w,projects:[],assignments:[]});
assert.equal((withoutProject.match(/未关联项目/g)??[]).length,4);
const withoutOwners=renderRegistrationTechnicalInfo(page,{...w,projects:[{id:'p',name:'商品中心',productOwner:' '}]});
assert.equal((withoutOwners.match(/>—<\/dd>/g)??[]).length,2);
