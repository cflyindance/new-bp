"""Generate local PNG fixtures, not customer campaign assets. Run from admin-web."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import json

out=Path('public/ad-default-demo');out.mkdir(parents=True,exist_ok=True)
font_path='C:/Windows/Fonts/msyh.ttc'
cases=[
 ('kiosk-idle-p',1080,1920,'招牌美味，随时欢迎','新鲜现做 · 扫码点餐','#173b31'),
 ('kiosk-idle-l',1920,1080,'招牌美味，随时欢迎','新鲜现做 · 轻松点餐','#173b31'),
 ('kiosk-home-p',1080,1250,'今天，吃点喜欢的','招牌烤鸡 · 时令沙拉','#9c3b22'),
 ('kiosk-home-l',1440,1080,'今天，吃点喜欢的','招牌烤鸡 · 时令沙拉','#9c3b22'),
 ('kiosk-cart',1280,720,'搭配一份，更有滋味','酥脆薯条 · 清爽饮品','#805222'),
 ('emenu-idle',1080,1920,'好好吃饭，慢慢享用','欢迎光临 · 新鲜食材','#354665'),
 ('emenu-menu',1280,720,'发现本店招牌','随时查看菜单 · 按需加购','#256257'),
 ('cds-idle',1920,1080,'感谢光临，期待再见','保留小票 · 留意取餐信息','#5c385c'),
 ('pickup-banner',1280,720,'美味正在准备中','请留意叫号 · 按序取餐','#245579'),
 ('waitlist-side',720,1280,'等位时，先看看招牌','烤鸡 · 沙拉 · 清爽饮品','#624b79'),
]
manifest={}
for key,w,h,title,detail,color in cases:
 for variant in [1,2]:
  img=Image.new('RGB',(w,h),color);d=ImageDraw.Draw(img);u=min(w,h);pad=int(u*.075)
  font=lambda n:ImageFont.truetype(font_path,int(u*n))
  d.rounded_rectangle((pad,pad,pad+u*.32,pad+u*.085),radius=8,fill='#f2e4c4')
  d.text((pad+u*.018,pad+u*.012),'门店常驻推荐',font=font(.038),fill=color)
  # A simple dish illustration leaves all promotional claims and prices out of the fixture.
  cx,cy=(w*.72,h*.64) if w>h else (w*.51,h*.65);r=u*.23
  d.ellipse((cx-r,cy-r,cx+r,cy+r),fill='#f4edda',outline='#ddd3b7',width=max(2,int(u*.007)))
  for dx,dy,size,fill in [(-.1,-.02,.10,'#d68842'),(.08,.04,.085,'#af5c27'),(-.02,.12,.045,'#e4a147'),(.09,-.11,.047,'#60913b'),(-.13,.11,.04,'#4b7f35')]:
   x,y=cx+u*dx,cy+u*dy;rr=u*size;d.ellipse((x-rr,y-rr,x+rr,y+rr),fill=fill)
  content=title if variant==1 else '用心准备每一餐'
  max_chars=9 if w<h else 14;lines=[content[i:i+max_chars] for i in range(0,len(content),max_chars)]
  y=h*.25
  for line in lines:d.text((pad,y),line,font=font(.071),fill='#fff8e7');y+=u*.105
  d.text((pad,y+u*.025),detail if variant==1 else '新鲜现做 · 品质食材',font=font(.029),fill='#f0e5d1')
  d.line((pad,h-pad-u*.08,w-pad,h-pad-u*.08),fill='#c1b39e',width=2)
  d.text((pad,h-pad-u*.06),'DEMO · 演示素材  '+str(variant).zfill(2),font=font(.024),fill='#eadfc9')
  filename=f'{key}-{variant}.png';path=out/filename;img.save(path,optimize=True)
  manifest[f'{key}-{variant}']={'file':filename,'width':w,'height':h,'bytes':path.stat().st_size}
Path('src/marketing-display/default-ad-demo-assets.ts').write_text('// Generated by scripts/generate-default-ad-demo.py\nexport const defaultAdDemoAssets = '+json.dumps(manifest,ensure_ascii=False,indent=2)+' as const;\n',encoding='utf-8')
print(f'Generated {len(manifest)} PNG assets')
