// Task-owned isolated browser only. CLI: playwright-cli run-code --filename scripts/verify-m-role-editor.browser.js
async (page) => {
  const out='docs/项目文档/images/m-role-editor-20261116/';
  const check=(value,message)=>{if(!value)throw Error(message);};
  const shot=async name=>{await page.screenshot({path:out+name+'.png',fullPage:true});};
  const grant=(key,value)=>page.locator('[data-grant="'+key+'"][data-value="'+value+'"]').last();
  await page.setViewportSize({width:1440,height:960});
  await page.getByRole('button',{name:'返回',exact:true}).click();
  await page.getByRole('heading',{name:'平台管理角色与权限',exact:true}).last().waitFor();
  await shot('01-list');
  await page.locator('a[href="#/m-platform/permissions/roles/edit/m-demo-merchant"]').click();
  await page.locator('[data-page="m:module:merchants"]').click();
  await shot('02-module');
  await page.locator('[data-menu-node="m:module:merchants"] > summary').click({position:{x:4,y:12}});
  check(!(await page.locator('[data-menu-node="m:module:merchants"]').getAttribute('open')),'module collapses');
  await shot('03-collapsed');
  await page.locator('[data-menu-node="m:module:merchants"] > summary').click({position:{x:4,y:12}});
  await page.locator('[data-page="m:page:stores"]').click();
  await shot('04-page');
  const original=await page.evaluate(async()=>{const m=await import('/src/permissions/m-platform-store.ts');return {m:localStorage.getItem(m.M_PERMISSION_STORAGE),merchant:localStorage.getItem('menusifu:provider-merchant-access:v1'),revision:m.readMState().revision};});
  await grant('m:page:stores','edit').click();
  await grant('m:action:stores:status','edit').click();
  await shot('05-edit-write');
  await grant('m:page:stores','read').click();
  check(await grant('m:action:stores:status','edit').isDisabled(),'write disabled by readonly page');
  check(!(await grant('m:action:stores:impersonate','edit').isDisabled()),'output remains configurable');
  await shot('06-readonly');
  await grant('m:module:merchants','hidden').click();
  check(await grant('m:page:stores','read').isDisabled(),'hidden parent gates page');
  await shot('07-hidden-parent');
  await grant('m:module:merchants','read').click();
  await grant('m:page:stores','edit').click();
  check(await grant('m:action:stores:status','edit').getAttribute('aria-pressed')==='true','child grant retained');
  await page.getByRole('textbox',{name:'搜索菜单',exact:true}).fill('门店');
  await shot('08-search');
  await page.getByRole('textbox',{name:'搜索菜单',exact:true}).fill('不存在的菜单xyz');
  await shot('09-search-empty');
  await page.getByRole('textbox',{name:'搜索菜单',exact:true}).fill('');
  await page.getByRole('button',{name:'权限预览',exact:true}).click();
  check(await page.locator('[data-grant]').count()===0,'preview has no writable controls');
  check(await page.locator('[data-page="m:page:services"]').count()===0,'preview hides denied pages');
  await shot('10-preview');
  await page.getByRole('button',{name:'返回编辑',exact:true}).click();
  await shot('11-draft-return');
  await page.getByRole('button',{name:'保存授权',exact:true}).click();
  await page.locator('dialog').waitFor();
  await shot('12-save-confirm');
  await page.locator('dialog [data-cancel]').click();
  check(await page.getByRole('button',{name:'保存授权',exact:true}).isEnabled(),'cancel retains draft');
  await shot('13-save-cancel');
  await page.getByRole('button',{name:'保存授权',exact:true}).click();
  await page.locator('dialog button[type=submit]').click();
  await page.getByRole('button',{name:'保存授权',exact:true}).waitFor();
  check(await page.getByRole('button',{name:'保存授权',exact:true}).isDisabled(),'save clears dirty');
  const saved=await page.evaluate(async()=>{const m=await import('/src/permissions/m-platform-store.ts');return m.readMState();});
  check(saved.revision===original.revision+1,'exactly one revision written');
  check(saved.roles.find(r=>r.id==='m-demo-merchant').grants['m:action:stores:status']==='edit','write persisted');
  check(await page.evaluate(raw=>localStorage.getItem('menusifu:provider-merchant-access:v1')===raw,original.merchant),'merchant state untouched');
  await page.locator('[data-page="m:page:stores"]').click();
  await shot('14-saved');
  await grant('m:page:stores','read').click();
  await page.evaluate(()=>{window.__mRoleOriginalSet=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k==='menusifu:m-platform-permissions:v1')throw Error('受控验证：存储写入失败');return window.__mRoleOriginalSet.call(this,k,v);};});
  await page.getByRole('button',{name:'保存授权',exact:true}).click();
  await page.locator('dialog button[type=submit]').click();
  check((await page.locator('dialog .pc-error').innerText()).includes('存储写入失败'),'save failure visible');
  await shot('15-save-failure');
  await page.evaluate(()=>{Storage.prototype.setItem=window.__mRoleOriginalSet;delete window.__mRoleOriginalSet;});
  await page.locator('dialog [data-cancel]').click();
  page.once('dialog',dialog=>dialog.dismiss());
  await page.getByRole('button',{name:'返回',exact:true}).click();
  check(page.url().includes('/roles/edit/'),'leave cancel stays in editor');
  await shot('16-leave-cancel');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'返回',exact:true}).click();
  await page.getByRole('heading',{name:'平台管理角色与权限',exact:true}).last().waitFor();
  await shot('17-leave-discard');
  // Restore only this isolated browser's test role/storage snapshot.
  await page.evaluate(async raw=>{const m=await import('/src/permissions/m-platform-store.ts');if(raw===null)localStorage.removeItem(m.M_PERMISSION_STORAGE);else localStorage.setItem(m.M_PERMISSION_STORAGE,raw);},original.m);
  await page.reload();
  await page.locator('a[href="#/m-platform/permissions/roles/edit/m-demo-merchant"]').click();
  await page.locator('[data-page="m:module:merchants"]').click();
  return 'PASS: module/page structure, fold, ancestor retention, readonly writes, independent output, search/empty, preview/draft, save/cancel/success/failure, leave cancel/discard; isolated role restored.';
}
