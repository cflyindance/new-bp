import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const context=vm.createContext({structuredClone});
vm.runInContext(fs.readFileSync(new URL('../dist/Configuration center/assets/kiosk-ad-material-batch.js',import.meta.url),'utf8'),context);
const api=context.KioskAdMaterialBatch,slot={id:'slot',productLine:'Kiosk',code:'home',version:1};
const none={type:'none'},external={type:'external',scope:'brand',title:'Member',url:'https://example.test/a',openMode:'iframe'};
const current=[{assetId:'portrait-1',clickAction:none},{assetId:'landscape-1',clickAction:none},{assetId:'hidden-spec-1',clickAction:external}];
const originalOrder=current.map(a=>a.assetId).join(',');
let batch=api.captureBatch(current.slice(0,2),slot);assert.equal(api.applyBatch(batch,current,slot,external),2);
assert.deepEqual(current[2].clickAction,external,'unselected different specification is unchanged');
assert.notEqual(current[0].clickAction,current[1].clickAction,'each material owns a separate action object');
assert.equal(current.map(a=>a.assetId).join(','),originalOrder,'batch does not reorder materials');
const all=api.captureBatch(current,slot);assert.equal(api.applyBatch(all,current,slot,none),3,'all includes hidden specifications');
assert.equal(api.commonAction(current).mixed,false);
assert.equal(api.commonAction([{clickAction:{type:'none',scope:'brand'}},{clickAction:{scope:'brand',type:'none'}}]).mixed,false,'field insertion order does not create a mixed state');
current[0].clickAction=external;assert.equal(api.commonAction(current).mixed,true,'mixed values must never echo the first material as a shared value');
batch=api.captureBatch(current.slice(0,2),slot);const before=JSON.stringify(current);current[1].clickAction=external;const changed=JSON.stringify(current);
assert.throws(()=>api.applyBatch(batch,current,slot,none),/已变化/);assert.equal(JSON.stringify(current),changed,'stale target never causes partial writes');
current[1].clickAction=none;batch=api.captureBatch(current.slice(0,2),slot);
assert.throws(()=>api.applyBatch(batch,current.slice(0,1),slot,none),/已移除/);assert.equal(JSON.stringify(current),before);
assert.throws(()=>api.applyBatch(batch,current,{...slot,version:2},none),/规格已变化/);assert.equal(JSON.stringify(current),before);
assert.throws(()=>api.captureBatch([],slot),/至少选择/);
assert.throws(()=>api.captureBatch([{assetId:'a'},{assetId:'a'}],slot),/标识异常/);
console.log('PASS all/spec subset selection, independent action copies, mixed state, stale actions, deleted assets, changed target, no partial writes or reordering');
